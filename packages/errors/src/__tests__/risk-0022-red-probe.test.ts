// ── مِجَسٌّ أحمرُ متعمَّدٌ · RISK-0022 ────────────────────────────────────
// هذا الملفُّ **يُخفِقُ بقصدٍ**، ووجودُه مؤقَّتٌ في فرعِ المِجَسِّ وحدَه ولا
// يُدمَجُ أبداً.
//
// **الدعوى المطلوبُ برهانُها:** أنّ الفحصَينِ المطلوبَينِ `test` و`typecheck`
// صارا **قادرَينِ على الإخفاقِ** بعدَ إدخالِ `set -o pipefail` في خطوتَيهما
// ([PR #28](https://github.com/skyosv10-art/wasla/pull/28) · `RISK-0022`).
// وقبلَ الإصلاحِ كانت حالةُ خروجِ الأنبوبِ حالةَ `tee` وهو ينجحُ دائماً،
// فكانت خضرتُهما تعني «لم يُقَسْ» لا «نجحَ».
//
// **ولا يُقبَلُ الإصلاحُ بقراءةِ نصِّه:** نصَّ سجلُّ المخاطرِ صراحةً أنّ الخطرَ
// لا يُعَدُّ معالَجاً «حتّى يُرى `test` أحمرَ به». فهذا المِجَسُّ هو ذلك
// البرهانُ، لا إعادةُ صياغةٍ له.
//
// وفيه عطبانِ مقصودانِ، كلٌّ منهما يُنيرُ فحصاً واحداً:
//   1. توكيدٌ يُخفِقُ            → يُثبِتُ أنّ `test` يُخفِقُ.
//   2. عدمُ تطابقٍ في الأنواعِ   → يُثبِتُ أنّ `typecheck` يُخفِقُ.
import { describe, expect, it } from 'vitest';

// العطبُ الثاني: `string` تُسنَدُ إلى `number` — خطأٌ نوعيٌّ صريحٌ يلتقطه
// `tsc --noEmit` ولا يلتقطه مُحوِّلُ vitest (esbuild لا يفحصُ الأنواعَ)،
// فيبقى العطبُ الأوّلُ مقيساً في `test` مستقلّاً عن هذا.
const deliberateTypeError: number = 'RISK-0022 · نوعٌ مخالفٌ بقصدٍ';

describe('RISK-0022 · مِجَسٌّ أحمرُ متعمَّدٌ (لا يُدمَجُ)', () => {
  it('يُخفِقُ بقصدٍ ليُقاسَ أنّ فحصَ `test` صارَ قادراً على الإخفاقِ', () => {
    expect('deliberate-red-probe').toBe('this-assertion-must-fail');
  });

  it('يُبقي الخطأَ النوعيَّ مُستعمَلاً كي لا يُحذَفَ بالتشذيبِ', () => {
    expect(typeof deliberateTypeError).toBe('string');
  });
});
