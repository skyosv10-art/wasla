#!/usr/bin/env bash
# claims_rows.sh — **قارئٌ واحدٌ** لصفوفِ الحجوزاتِ النشطةِ في WORK_CLAIMS.md.
#
# **العطبُ المقيسُ الذي أوجبَ هذا الملفَّ (M0-38 · 2026-09-14):** كانَ للسجلِّ
# الواحدِ **قارئانِ بقاعدتَينِ مختلفتَينِ**:
#   · `validate-work-claims.sh` يقرأُ الحالةَ **مطابقةً تامّةً**: `$9 != "Active"`،
#   · `validate-claim-freshness.sh` يقرأُها **احتواءً**: `$9 ~ /Active/`،
# وفي رأسِ الثاني مكتوبٌ أنّهُ «عينُ ما يفعلُهُ» الأوّلُ — فكانَ **التوثيقُ يشهدُ
# باتّفاقٍ غيرِ قائمٍ**. وقد ظهرَ الفرقُ بالقياسِ لا بالتخيُّلِ: صفٌّ حُرِّرَ ودليلُ
# تحريرِهِ يذكرُ حرفيّاً أنَّ «عمودَ الحالةِ بقيَ `Active`» — فقرأهُ الأوّلُ محرَّراً
# (صواباً) وقرأهُ الثاني نشطاً (خطأً) فأسقطَ البوّابةَ على حجزٍ لا وجودَ لهُ.
#
# **والقاعدةُ هنا واحدةٌ لا اثنتانِ:** الحالةُ `Active` أو `Paused` **مطابقةً تامّةً**
# بعدَ قصِّ الفراغِ — فما زادَ عليها نصٌّ (دليلُ إفراجٍ · سجلٌّ تدقيقيٌّ) ليسَ حالةً.
# و`Paused` تُقرأُ حجزاً قائماً لأنّها ما زالت تُقفِلُ النطاقَ ([§2](../../../docs/00-rules/WORK_CLAIM_RULE.md)).
#
# الاستعمالُ: `claims_active_rows <claims-file>` → أسطرٌ مفصولةٌ بـtab:
#   cid \t item \t owner \t branch \t scope \t started \t expires \t status
claims_active_rows() {
  local file="$1"
  awk -F'|' '
    /^\| *CLM-[0-9]+ *\|/ {
      for (i = 2; i <= NF; i++) { gsub(/^[ \t]+|[ \t]+$/, "", $i) }
      if (NF < 9) next
      if ($9 != "Active" && $9 != "Paused") next
      print $2 "\t" $3 "\t" $4 "\t" $5 "\t" $6 "\t" $7 "\t" $8 "\t" $9
    }
  ' "$file"
}
