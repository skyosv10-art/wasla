#!/usr/bin/env bash
# meaningful-paths.sh — مصدرٌ واحدٌ لمرشِّحِ «التغييراتِ ذاتِ المعنى». (M0-15)
#
# ── لماذا يوجد هذا الملف ──────────────────────────────────────────────────
# كان المرشِّحُ مكتوباً **مرتَّينِ حرفيّاً**: `MEANINGFUL` في validate-work-claims.sh
# و`CODE_OR_CONFIG_PATHS` في require-doc-update.sh. وقائمةُ السجلاتِ المشتركةِ يحرسُ
# تطابقَها check-shared-ledgers.py في أربعةِ مواضعَ لأنّ انحرافَها **لا يُكتشف
# بالقراءةِ** — كلُّ موضعٍ صحيحٌ وحدَه ولا يظهر الفرقُ إلّا بالمقارنة (M0-12/M0-13).
# أمّا المرشِّحُ فكان **بلا حارسٍ إطلاقاً**، وانحرف فعلاً: `docs/` كان في نسخةِ
# require-doc-update وليس في نسخةِ validate-work-claims — وهو عيبُ M0-14 نفسُه،
# ومعه تعليقٌ فوقَ `MEANINGFUL` يقول «نفس تعريف require-doc-update.sh» وكان **غيرَ
# صحيحٍ** سنةً كاملةً من عمرِ الملف.
#
# والعلاجُ هنا **مصدرٌ واحدٌ لا حارسُ تطابقٍ لنسختَين**: الحارسُ يكشف الانحرافَ بعدَ
# وقوعِه، والمصدرُ الواحدُ يمنع وقوعَه. (قائمةُ السجلاتِ المشتركةِ تبقى في مواضعِها
# الأربعةِ بحارسِها: موضعانِ منها **وثيقتانِ حاكمتان** تُقرأانِ بالعينِ، فلا يصحُّ
# إخفاؤهما في سكربت. الفرقُ مقصود.)
#
# ── الاستخدام ─────────────────────────────────────────────────────────────
#   source "$(dirname "$0")/lib/meaningful-paths.sh"
#   $CODE_OR_CONFIG_PATHS   → الكودُ والإعداداتُ وحدَها (لا وثائق)
#   $MEANINGFUL_PATHS       → الكودُ والإعداداتُ **و`docs/`**
#
# لا `set -e` ولا `exit` هنا: الملفُّ يُستدعى بـsource داخلَ سكربتاتٍ لها إعدادُها.

# البادئاتُ التي تُوجب حجزاً وتوثيقاً — تُحرَّر هنا وحدَها.
CODE_OR_CONFIG_PATHS='^(apps/|bots/|services/|packages/|infra/|scripts/|\.gitlab-ci\.yml$|package\.json$|pnpm-lock\.yaml$|README\.md$|CONTRIBUTING\.md$|SECURITY\.md$)'

# ويُشتقُّ مرشِّحُ الحجزِ بإضافةِ `docs/` — بتوسيعِ مُعامِلٍ في bash لا بأنبوبٍ ولا
# بنسخةٍ ثانيةٍ من القائمة، فلا موضعَ انحرافٍ ثانٍ يُخلَق من حيث عولِج الأوّل.
# (السجلاتُ المشتركةُ الخمسةُ تُستثنى عندَ الاستعمالِ بـis_shared()/LEDGER_ONLY_PATHS،
#  لا هنا: القاعدةُ تُلزم كلَّ دافعٍ بتحديثِها فلا يجوز أن تُوجب حجزاً — M0-14.)
MEANINGFUL_PATHS="${CODE_OR_CONFIG_PATHS/'^('/'^(docs/|'}"
