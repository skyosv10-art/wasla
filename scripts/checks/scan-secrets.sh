#!/usr/bin/env bash
# scan-secrets.sh — فحص عدم وجود أسرار في الملفات المتتبعة (Tracked files only).
#
# يحل مشكلة الفحص القديم الذي كان يستعمل `grep -r .` فكان يطابق:
#   1. مجلد .git (ملفات ثنائية) — يسبب إيجابيات كاذبة.
#   2. ملف .gitlab-ci.yml نفسه — لأنه يحتوي على أنماط الكشف كنص حرفي.
#
# الحل: `git grep` يفحص الملفات المتتبعة فقط (يتجاهل .git تلقائياً)،
# مع استثناء ملفات «الكاشف» نفسها لأنها تحتوي على توقيعات الكشف لا أسراراً.
#
# يُستعمل من:
#   - .gitlab-ci.yml :: repo-structure  (إلزام خادمي على كل pipeline)
#   - scripts/hooks/pre-push            (إلزام محلي قبل الدفع — تنبيه مبكر)
#
# الاستخدام:
#   scan-secrets.sh            # يفحص كل الملفات المتتبعة
#
# Exit codes:
#   0 = لم يُعثر على أنماط أسرار (أو لسنا داخل مستودع git)
#   1 = عُثر على نمط سر محتمل
set -euo pipefail

# أنماط الكشف عن الأسرار الشائعة.
# ملاحظة: هذه الأنماط مكتوبة كنص حرفي داخل هذا الملف، لذلك يستثني الفحص
# هذا الملف وملف .gitlab-ci.yml صراحةً أدناه (كلاهما يحوي توقيعات الكشف لا أسراراً).
# ── إصلاحُ إيجابيّةٍ كاذبةٍ (M0-07) ──────────────────────────────────────
# كان النمطُ `sk-[0-9A-Za-z]` **بلا حدِّ كلمةٍ ولا حدِّ طولٍ**، فطابقَ كلَّ سطرٍ
# فيه كلمةٌ عربيّةٌ الحرفُ اللاتينيُّ فيها `risk-…`: أسقطَ الفحصُ السادسُ البوّابةَ
# كلَّها على `validate-risk-register.sh` و`RISK_REGISTER.md` — أي أنّ الحارسَ
# كان يمنع دفعاً سليماً ويُدرِّب من يقرؤه على تجاهلِ إنذارِ أسرارٍ. وذاك أسوأُ من
# ثغرةٍ: حارسٌ يصرخ بلا سببٍ يُعلَّم الناسُ إسكاتَه.
# العلاجُ: حدُّ كلمةٍ قبلَ البادئةِ، وأطوالٌ واقعيّةٌ لكلِّ توقيعٍ (مفتاحُ OpenAI
# ≥20 محرفاً · AKIA 16 · ghp_ 36 · glpat 20). **وما فقدناه يُقال:** توقيعٌ مبتورٌ
# قصيرٌ جدّاً لم يُعَد يُطابَق — وهو مقصودٌ: النمطُ القديمُ كان يطابق شبهَ الحرفَين.
PATTERN='((^|[^0-9A-Za-z_-])sk-[0-9A-Za-z]{20,}|AKIA[0-9A-Z]{16}|ghp_[0-9A-Za-z]{36}|glpat-[0-9A-Za-z_-]{20}|BEGIN (RSA |EC )?PRIVATE KEY)'

# ملفات الكاشف التي تحتوي على الأنماط كتعريفات (ليست أسراراً) — تُستثنى.
# pathspec بـ :! يُطبَّق بالنسبة لجذر المستودع.
EXCLUDES=(
  ':!/.gitlab-ci.yml'
  ':!/scripts/checks/scan-secrets.sh'
)

if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  echo "تخطّي الفحص: لسنا داخل مستودع git." >&2
  exit 0
fi

# الفحص الشامل: كامل الملفات المتتبعة ما عدا ملفات الكاشف.
if git grep -nE "$PATTERN" -- "${EXCLUDES[@]}" >/dev/null 2>&1; then
  echo "ERROR: عُثر على نمط سر محتمل في الملفات المتتبعة:" >&2
  git grep -nE "$PATTERN" -- "${EXCLUDES[@]}" >&2 || true
  exit 1
fi

echo "OK: لا أنماط أسرار واضحة في الملفات المتتبعة (باستثناء ملفات الكاشف)." >&2
exit 0
