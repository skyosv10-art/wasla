# ومحرِّكُ القياسِ في وحدةٍ واحدةٍ تُقرأُ وتُختَبَرُ: مصدرُ حقيقةٍ واحدٌ لا اثنان.
exec python3 scripts/checks/lib/app_port_wiring.py "$DOC"
