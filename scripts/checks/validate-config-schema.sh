#!/usr/bin/env bash
# validate-config-schema.sh — حارسُ **مصدرِ الحقيقةِ الواحدِ** لإعدادِ البيئةِ. (M2-04)
#
# ── العطبُ المحروسُ ───────────────────────────────────────────────────────
# قِيسَ على `main` قبلَ هذا الحارسِ:
#   · **59 متغيّرَ بيئةٍ** تُقرأُ في 140 موضعاً، ولا ملفَّ واحدَ يُعلِنُ أيُّها
#     إلزاميٌّ ولا أيُّ نوعٍ لهُ. و`.env.example` **لم يكنْ موجوداً**، فالنشرةُ
#     الأولى تُكتَشَفُ نواقصُها بالسقوطِ لا بالقراءةِ.
#   · **17 قراءةً رقميّةً عاريةً** بـ`Number(process.env.X ?? n)`. و`Number` لا
#     يُلقي: `Number("٣") ⇒ NaN` و`Number("") ⇒ 0` و`Number("0x10") ⇒ 16`. فقيمةٌ
#     مكتوبةٌ بأرقامٍ عربيّةٍ-هنديّةٍ في جَدوَلِ نشرةٍ تُنتِجُ `waveSize = NaN`
#     و**موجةَ إرسالٍ بلا سائقٍ واحدٍ، والخدمةُ حيّةٌ تُجيبُ 200 على صحّتِها**.
#     لا `tsc` يراهُ (`NaN` نوعُهُ `number`) ولا اختبارٌ ولا سجلٌّ (`RISK-0046`).
#   · **أربعُ نسخٍ** من القارئِ الصارمِ في أربعةِ ملفّاتٍ برسائلَ مختلفةٍ — فالصرامةُ
#     صدفةُ ملفٍّ لا قاعدةُ مستودعٍ.
#
# ── لماذا حارسٌ ولا يكفي اختبارٌ ───────────────────────────────────────────
# لأنَّ ما يُحرَسُ هنا **علاقةُ ملفَّينِ لا سلوكُ دالّةٍ**: أن يكونَ `.env.example`
# و`registry.generated.ts` **مُشتَقَّينِ** من السجلِّ بايتاً بايتاً، وأن لا تُقرأَ
# في الشجرةِ قراءةٌ غيرُ مُعلَنةٍ، وأن لا يُعلَنَ متغيّرٌ لا يُقرأُ. واختبارُ حزمةٍ
# يرى حزمتَهُ وحدَها، وهذهِ الحُجَجُ تمسُّ 26 خدمةً وثلاثةَ بوتاتٍ معاً.
#
# ── الأبوابُ الثمانيةُ ────────────────────────────────────────────────────
# 1) لا قراءةَ غيرَ مُسجَّلةٍ · 2) لا إعلانَ ميّتاً · 3) المُشتَقُّ = إعادةُ توليدِهِ
# 4) سلامةُ السجلِّ بنيويّاً · 5) الاسمُ يُلزِمُ نوعَهُ · 6) لا تحليلَ رقميّاً عارياً
# 7) كلُّ سرٍّ نائبٌ في المثالِ · 8) القارئُ غيرُ المباشرِ مُعلَنٌ ومربوطٌ حرفاً
#
# والمنطقُ كلُّهُ في `lib/config_schema_semantics.py` لأنَّ القياسَ يحتاجُ نزعَ
# تعليقاتٍ ومسحَ شجرةٍ وتوليداً مُقارَناً — وbash يجعلُ ذلكَ هشّاً. وهذا المِغلافُ
# يبقى ليكونَ الحارسُ **مربوطاً في `verify-governance.sh`** بالصيغةِ نفسِها التي
# تربطُ إخوتَهُ، فلا يصيرَ حارساً يتيماً يرفضُهُ `validate-ci-mandatory.sh`.
#
# المرجع: docs/08-infrastructure/CONFIG_SCHEMA.md · ADR-032 · docs/12-testing/M2-04_GATE.md
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

RED=$'\033[31m'; RST=$'\033[0m'

if ! command -v python3 >/dev/null 2>&1; then
  # لا تخطٍّ صامتاً: غيابُ المُفسِّرِ يُعطِّلُ الحارسَ، وحارسٌ مُعطَّلٌ أسوأُ من
  # غيابِهِ لأنَّهُ يُقرأُ خُضرةً. (وهوَ عينُ ما وقعَ في الفحصِ 14 قبلَ M0-42.)
  printf '%s✗%s python3 مفقودٌ — حارسُ مخطَّطِ الإعدادِ لا يُخطَّى\n' "$RED" "$RST" >&2
  exit 1
fi

exec python3 scripts/checks/lib/config_schema_semantics.py --check --root "$ROOT"
