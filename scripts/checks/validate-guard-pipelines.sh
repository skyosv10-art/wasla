#!/usr/bin/env bash
# validate-guard-pipelines.sh — لا أنبوبَ يُغذّي `grep -q` في حارسٍ (`RISK-0037`)
#
# **السؤالُ:** أفي نصوصِ الحرّاسِ مقارنةٌ يُقرَأُ فيها **سباقُ إشارةٍ** حكماً على
# عملِ المُطوِّرِ؟
#
# **العطبُ المقيسُ، لا المُتوقَّعُ:** `printf '%s\n' "${ARR[@]}" | grep -qxF "$x"`
# تحتَ `set -o pipefail` — يخرجُ `grep` عندَ **أوّلِ** تطابقٍ فيُغلِقُ الأنبوبَ،
# فيموتُ المُنتِجُ بـ`SIGPIPE`، فتصيرُ حالةُ الأنبوبِ **141**، فيقرأُها الشرطُ
# **«لا تطابق»** فيَرفُضُ عملاً صحيحاً. مقيساً بـ300 إعادةٍ: **9 رفضاتٍ كاذبةٍ
# للمقارنةِ الواحدةِ · 0 من 300 بلا أنبوبٍ** (2026-09-13 · `RISK-0037`).
#
# **ولمَ حارسٌ لا رقعةٌ:** العطبُ نفسُه عُولِجَ مرّتَينِ من قبلُ — في
# `require-doc-update.sh` و`validate-launch-board.sh` — وكُتِبَ تعليلُه حرفاً في
# كلٍّ منهما، **ثمَّ عادَ في حارسٍ ثالثٍ** (`validate-service-auth-coverage.sh`)
# ورابعٍ (`validate-baseline.sh`) وخامسٍ (`validate-migrations.sh`). فالعلاجُ
# الموضعيُّ ثلاثَ مرّاتٍ أثبتَ أنّه لا يمنعُ العودةَ: **النمطُ كانَ مسموحاً.**
# «عطبٌ معروفٌ يُترَكُ ليقعَ مرّةً أخرى ليسَ سهواً بل قراراً».
#
# **وخطرُه ليسَ إزعاجاً:** حارسٌ يرفضُ الصحيحَ باحتمالٍ يُعلِّمُ المُشغِّلَ أن
# يُعيدَ التشغيلَ حتّى يخضرَّ — فيصيرُ الرفضُ **الصادقُ** مُعادَ التشغيلِ أيضاً.
# أي أنّه **يُفسِدُ معنى الأحمرِ** في البوّابةِ كلِّها لا في حارسٍ واحدٍ.
#
# **الرقعةُ المقبولةُ** واحدةٌ من اثنتَينِ، ولا ثالثةَ:
#   • `grep -q '…' <<< "$نص"`            (نصٌّ جاهزٌ — لا أنبوبَ ولا مُنتِجٌ يُقتَل)
#   • مقارنةٌ في الغلافِ نفسِه على عنصرٍ عنصرٍ (`has_exact` في حارسِ التغطيةِ)
# ولا تُقبَلُ رقعةٌ بـ`|| true` ولا بإلغاءِ `pipefail`: كلتاهما تُخفيانِ إخفاقاً
# حقيقيّاً في المُنتِجِ أيضاً — أي تُخفِّفانِ الحارسَ بدلَ أن تُصلِحاهُ.
#
#   bash scripts/checks/validate-guard-pipelines.sh            # المستودعُ نفسُه
#   bash scripts/checks/validate-guard-pipelines.sh /tmp/root  # جذرٌ صريحٌ (للاختبار)
#
# الخروجُ 0 إن خلَت النصوصُ، و1 مع **كلِّ** موضعٍ (لا أوّلِ موضعٍ فقط).
# المرجع: docs/07-security/RISK_REGISTER.md `RISK-0037` · docs/00-rules/VERIFY_COMMAND.md

set -uo pipefail

ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"
cd "$ROOT" || { echo "تعذّر الوصول إلى الجذر: $ROOT" >&2; exit 1; }

RED=$'\033[31m'; GRN=$'\033[32m'; DIM=$'\033[2m'; RST=$'\033[0m'

# تُبنى الإبرةُ من قطعٍ حتّى لا يُطابِقَ الحارسُ **نفسَه** فيُصبحَ إخفاقاً
# أبديّاً — ولا يُستثنى ملفٌّ بالاسمِ (استثناءُ ملفٍّ يفتحُ باباً لاستثناءِ غيرِه).
P='\|'   # أنبوبٌ **حرفيٌّ** لا «أو» في ERE — وإغفالُ الهروبِ يطابقُ كلَّ سطرٍ
NEEDLE="[^<]${P}[[:space:]]*grep[^${P}]*[[:space:]]-[a-zA-Z]*q"

mapfile -t SCRIPTS < <(find scripts -name '*.sh' -type f | sort)
if (( ${#SCRIPTS[@]} == 0 )); then
  printf '%s✗ لا نصَّ حارسٍ واحدٌ تحتَ scripts/ — تغيَّرَ الترتيبُ والحارسُ يفحصُ فراغاً.%s\n' "$RED" "$RST"
  exit 1
fi

HITS=()
for f in "${SCRIPTS[@]}"; do
  # تُسقَطُ أسطرُ التعليقِ: التعليلُ المكتوبُ لعطبٍ **مُعالَجٍ** يذكرُ النمطَ نصّاً،
  # ومنعُ ذكرِه يمحو الدليلَ الذي يمنعُ عودتَه. الشفرةُ وحدَها تُحاسَب.
  while IFS= read -r hit; do
    [[ -n "$hit" ]] && HITS+=("$f:$hit")
  done < <(grep -nE "$NEEDLE" "$f" | grep -vE '^[0-9]+:[[:space:]]*#')
done

if (( ${#HITS[@]} )); then
  printf '%s✗ أنبوبٌ يُغذّي grep -q في %d موضعاً — سباقُ SIGPIPE يُقرَأُ «لا تطابق» (RISK-0037):%s\n' \
    "$RED" "${#HITS[@]}" "$RST"
  for h in "${HITS[@]}"; do printf '  ✗ %s\n' "$h"; done
  printf '%s  الرقعةُ: grep -q … <<< "$نص"  أو مقارنةٌ في الغلافِ على عنصرٍ عنصرٍ.\n' "$DIM"
  printf '  ولا تُقبَلُ «|| true» ولا إلغاءُ pipefail: إخفاءُ إخفاقٍ لا إصلاحُ عطبٍ.%s\n' "$RST"
  exit 1
fi

printf '%s✓ لا أنبوبَ يُغذّي grep -q:%s %d نصَّ حارسٍ مفحوصاً — العضويّةُ حتميّةٌ لا احتماليّةٌ.\n' \
  "$GRN" "$RST" "${#SCRIPTS[@]}"
printf '%s  المرجعُ: RISK-0037 (مقيسٌ: 9/300 رفضاً كاذباً بالأنبوبِ · 0/300 بدونِه)%s\n' "$DIM" "$RST"
exit 0
