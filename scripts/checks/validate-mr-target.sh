#!/usr/bin/env bash
# validate-mr-target.sh — يحرس **هدفَ الطلبِ** لا محتواه. (M0-17)
#
#   bash scripts/checks/validate-mr-target.sh [TARGET_BRANCH] [DEFAULT_BRANCH]
#
# ويقرأ عندَ غيابِ الوسائطِ متغيّراتِ GitLab: `CI_MERGE_REQUEST_TARGET_BRANCH_NAME`
# و`CI_DEFAULT_BRANCH`. فيعمل في وظيفةِ `governance-guard` بلا تهيئةٍ إضافيّة.
#
# ── لماذا يوجد هذا الفحص ──────────────────────────────────────────────────
# في 2026-08-27 وقعَ عيبٌ تشغيليٌّ حقيقيٌّ لا فرضيّ: فرعُ `M0-16` بُني على
# `chore/m0-15-closeout` وهُدف إليه، فلمّا دُمج [MR !95] إلى `main` **أوّلاً** ثمّ
# دُمج [MR !96] إلى ذلك الفرعِ **بعدَه**، بقي عملُ `M0-16` كلُّه خارجَ `main`
# (`404 File Not Found` على `validate-claim-freshness.sh?ref=main`) واحتاج
# [MR !97] لنقلِه بلا سطرٍ جديد. أي أنّ الطلبَ **دُمج بنجاحٍ** ولم يبلغ العملُ
# أحداً — والبوّابةُ كلُّها خضراءُ، لأنّ لا فحصَ يسأل: **إلى أين يُدمَج هذا؟**
#
# وهذا خامسُ انحرافٍ من جنسٍ واحد: `M0-12` (قائمةٌ في ثلاثةِ مواضعَ تختلف) ·
# `M0-14` (`docs/` خارجَ المرشِّح) · `M0-15` (المرشِّحُ نسختان) · `M0-16` (السجلُّ
# يقول `Active` والفرعُ محذوف) · وهذا: **الهدفُ نفسُه لا يُسأل عنه.**
#
# ── الحكم ─────────────────────────────────────────────────────────────────
#   • الهدفُ الفرعُ الافتراضيُّ            → يمرّ.
#   • الهدفُ غيرُ موجودٍ في المستودعِ      → يُرفَض: لا فرعَ يُدمج إليه.
#   • الهدفُ لا يحمل التزاماً واحداً ليس   → يُرفَض: إمّا أنّه مدموجٌ أصلاً (عينُ
#     في الفرعِ الافتراضيِّ                  عيبِ !96 فيُعلَق عملُك خارجَ `main`)،
#                                           وإمّا أنّه فرعٌ فارغٌ مساوٍ له فلا
#                                           سببَ لاستهدافِه بدلَ `main`. وفي
#                                           الحالتَينِ الصوابُ استهدافُ الافتراضيّ.
#   • الهدفُ متقدِّمٌ بالتزامٍ أو أكثر      → يمرُّ **بتنبيهٍ**: طلبٌ مكدَّسٌ مشروعٌ.
#
# ── حدُّ هذا الفحصِ المُعلَن ────────────────────────────────────────────────
# يحكم على **حالةِ الفرعِ الهدفِ في شجرةِ الالتزامات** فقط. ولا يعرف حالةَ طلبِ
# الدمجِ الخاصِّ بالهدفِ في GitLab (مفتوحٌ؟ مُغلَق؟) — فلا يستطيع أن يضمن أنّ هدفاً
# متقدِّماً سيُدمج لاحقاً؛ يمرِّره وينبِّه، ولا يُدَّعى أكثر. وإن تعذّر معرفةُ الهدفِ
# أو سؤالُ المستودعِ عنه **يُعلَن التخطّي صريحاً ولا يُدَّعى النجاح**: فحصٌ يصمت
# عندَ الجهلِ أسوأُ من غيابِه (عينُ ما قُرِّر في `M0-16`).
#
# ويُفرَّق هنا بين حالتَينِ لا تُخلَطان، لأنّ خلطَهما إمّا يُجمِّل جهلاً وإمّا يُشيع
# تنبيهاً كاذباً في كلِّ خطٍّ على `main`:
#   • **جهلٌ** — هناك هدفٌ ولم أستطع سؤالَ المستودعِ عنه → «تخطٍّ · جزئيٌّ» (يُحتسَب
#     تخطّياً في البوّابةِ الموحّدةِ فلا تُعلَن خضرةٌ كاملة).
#   • **لا موضوعَ للحكم** — ليس سياقَ طلبِ دمجٍ أصلاً (خطُّ `main`، أو تشغيلٌ يدويٌّ
#     بلا وسيط) → «لا ينطبق» ويُحتسَب مروراً، ويُطبَع سببُه في الخلاصةِ حرفيّاً فلا
#     يُوهم أنّ حكماً وقع. فليس عدمُ وجودِ الطلبِ نقصاً في الفحص.
set -uo pipefail

cd "$(dirname "$0")/../.." || { echo "تعذّر الوصول إلى جذر المستودع" >&2; exit 1; }

RED=$'\033[31m'; GRN=$'\033[32m'; YLW=$'\033[33m'; RST=$'\033[0m'

TARGET="${1:-${CI_MERGE_REQUEST_TARGET_BRANCH_NAME:-}}"
DEFAULT="${2:-${CI_DEFAULT_BRANCH:-main}}"

skip() { # skip <سبب> — جهلٌ مُعلَنٌ بلا ادّعاءِ نجاح
  printf '  %s⊘ تخطٍّ — %s%s\n' "$YLW" "$1" "$RST"
  printf '  %sالنجاحُ جزئيٌّ لا كامل: لم يُحكَم على هدفِ الطلب.%s\n' "$YLW" "$RST"
  exit 0
}

not_applicable() { # not_applicable <سبب> — لا موضوعَ للحكم، وليس جهلاً
  printf '  %s○ لا ينطبق — %s%s\n' "$YLW" "$1" "$RST"
  exit 0
}

git rev-parse --is-inside-work-tree >/dev/null 2>&1 || skip "لا مستودعَ git في هذا المسار"

if [[ -z "$TARGET" ]]; then
  not_applicable "ليس سياقَ طلبِ دمج (لا وسيطٌ ولا CI_MERGE_REQUEST_TARGET_BRANCH_NAME)"
fi

# ── الهدفُ هو الفرعُ الافتراضيُّ: الحالةُ السويّةُ وأكثرُها وقوعاً ─────────────
if [[ "$TARGET" == "$DEFAULT" ]]; then
  printf '  %s✓%s الهدفُ هو الفرعُ الافتراضيُّ «%s» — لا خطرَ عَلَق.\n' "$GRN" "$RST" "$DEFAULT"
  exit 0
fi

# ── حلُّ المرجعَين: محليّاً أوّلاً، ثمّ مرجعُ origin، ثمّ جلبٌ من البعيد ────────
TMP_NS="refs/gov-mr-target"
cleanup() { git for-each-ref --format='%(refname)' "$TMP_NS" 2>/dev/null | while read -r r; do git update-ref -d "$r" 2>/dev/null; done; }
trap cleanup EXIT

resolve() { # resolve <فرع> → يطبع sha أو يُرجِع 1
  local b="$1" sha=""
  for r in "refs/heads/$b" "refs/remotes/origin/$b" "$TMP_NS/$b"; do
    sha="$(git rev-parse --verify --quiet "$r" 2>/dev/null)" && { printf '%s' "$sha"; return 0; }
  done
  return 1
}

REMOTE_OK=0
if git remote get-url origin >/dev/null 2>&1; then
  git ls-remote --heads --quiet origin >/dev/null 2>&1 && REMOTE_OK=1
fi

fetch_if_needed() { # fetch_if_needed <فرع> → 0 إن صار محلولاً
  resolve "$1" >/dev/null && return 0
  (( REMOTE_OK )) || return 1
  # أهو موجودٌ في البعيدِ أصلاً؟ يُسأل قبلَ الجلبِ كي يُفرَّق «محذوفٌ» من «تعذّر الجلب».
  [[ -n "$(git ls-remote --heads origin "refs/heads/$1" 2>/dev/null)" ]] || return 2
  git fetch -q --depth=200 origin "+refs/heads/$1:$TMP_NS/$1" >/dev/null 2>&1 \
    || git fetch -q origin "+refs/heads/$1:$TMP_NS/$1" >/dev/null 2>&1 || return 1
  resolve "$1" >/dev/null
}

fetch_if_needed "$TARGET"; T_RC=$?
if (( T_RC == 2 )); then
  printf '\n%s✗ الفرعُ الهدفُ «%s» غيرُ موجودٍ في المستودع.%s\n' "$RED" "$TARGET" "$RST" >&2
  printf '  لا فرعَ يُدمج إليه — استهدف الفرعَ الافتراضيَّ «%s».\n' "$DEFAULT" >&2
  exit 1
fi
(( T_RC == 0 )) || skip "تعذّر حلُّ الفرعِ الهدفِ «$TARGET» (لا مرجعٌ محليٌّ ولا وصولٌ إلى origin)"

fetch_if_needed "$DEFAULT" || skip "تعذّر حلُّ الفرعِ الافتراضيِّ «$DEFAULT» — فلا مقارنةَ أسلافٍ ممكنة"

T_SHA="$(resolve "$TARGET")"
D_SHA="$(resolve "$DEFAULT")"

# ── الحكمُ: أيحمل الهدفُ التزاماً واحداً ليس في الافتراضيِّ؟ ──────────────────
if git merge-base --is-ancestor "$T_SHA" "$D_SHA" 2>/dev/null; then
  printf '\n%s✗ الفرعُ الهدفُ «%s» لا يحمل التزاماً واحداً ليس في «%s».%s\n' "$RED" "$TARGET" "$DEFAULT" "$RST" >&2
  printf '  فإمّا أنّه **مدموجٌ أصلاً** — فالدمجُ إليه يُعلِق عملَك خارجَ «%s» كما وقع\n' "$DEFAULT" >&2
  printf '  في MR !96 واحتاج MR !97 لنقلِه — وإمّا أنّه فرعٌ فارغٌ مساوٍ له فلا سببَ\n' >&2
  printf '  لاستهدافِه. وفي الحالتَينِ الصوابُ استهدافُ «%s».\n' "$DEFAULT" >&2
  printf '  المرجع: ROADMAP_OPERATING_PROTOCOL.md §7 · docs/00-rules/GIT_RULES.md\n' >&2
  exit 1
fi

AHEAD="$(git rev-list --count "$D_SHA..$T_SHA" 2>/dev/null || printf '؟')"
printf '  %s✓%s الهدفُ «%s» متقدِّمٌ على «%s» بـ%s التزاماً — طلبٌ مكدَّسٌ مشروع.\n' \
  "$GRN" "$RST" "$TARGET" "$DEFAULT" "$AHEAD"
printf '  %sتنبيه:%s الفحصُ يحكم على شجرةِ الالتزاماتِ لا على حالةِ طلبِ الهدفِ في GitLab —\n' "$YLW" "$RST"
printf '  فلا يضمن أنّ الهدفَ سيُدمج لاحقاً. اجعل دمجَ الهدفِ **قبلَ** دمجِ فرعِك، أو استهدف «%s».\n' "$DEFAULT"
exit 0
