#!/usr/bin/env bash
# validate-service-auth-coverage.sh — حارسُ تغطيةِ هويّةِ الخدمة (M1-03 · فحصُ 12).
#
# السّؤالُ الذي يجيبُ عنه هذا الفحصُ واحدٌ ومحدودٌ:
#
#   **هل دخلَ المستودعَ نداءٌ صادرٌ بين الخدماتِ لا يوقِّع، أو حدٌّ مُعلَنٌ مفروضاً
#   ولا إنفاذَ في شفرتِه — بلا إعلانٍ في سجلِّ التغطية؟**
#
# وليسَ السّؤالُ: «أهيَ التغطيةُ كاملةٌ؟» — فليستْ كاملةً، وهذا مُعلَنٌ لا مُداوى:
# دفعةُ M1-03 تُثبِتُ **حدَّ المطابقةِ** ببرهانٍ عبرَ مقبسٍ حقيقيّ، وتُؤجّلُ بقيّةَ
# الحدودِ إلى بوّابةِ M1-04 المستقلّة. فوظيفةُ هذا الحارسِ منعُ **الانحدارِ**: أن
# يُضافَ عميلٌ جديدٌ أو حدٌّ جديدٌ فيمرَّ بلا هويّةٍ وبلا أن يُذكرَ في السّجل.
#
# فهو إذن حارسُ **إعلانٍ صادقٍ**، لا شهادةُ اكتمال. ولذلك يرفضُ أمرَين متكافئَين في
# الخطر: عميلاً غيرَ موقِّعٍ لم يُعلَن، **وسجلاً يدّعي توقيعاً لا وجودَ له في الشفرة**.
#
# الأبوابُ الخمسةُ:
#   1) السّجلُّ موجودٌ وبصيغتِه: docs/07-security/SERVICE_AUTH_ENFORCEMENT.md
#   2) كلُّ عميلٍ صادرٍ على القرصِ مذكورٌ في السّجل — العميلُ الجديدُ يُسقِطُ الفحص.
#   3) كلُّ صفٍّ يقول «موقَّع» يُثبِتُه grep في الملفِّ نفسِه — لا سجلَّ يكذب.
#   4) كلُّ صفٍّ يقول «مؤجَّل» يحملُ مرجعَ البوّابةِ المؤجَّلِ إليها (M1-04).
#   5) كلُّ حدٍّ يقول السّجلُّ إنّه مفروضٌ فيه registerServiceIdentity فعلاً.
#   7) **لا مُناديَ خامٍ (`fetch(`) خارجَ بصرِ السّجلِّ** في services/ وbots/
#      وpackages/ — إمّا عميلٌ مُحصَىً، أو استثناءٌ مُعلَنٌ بسببِه (`RISK-0027`).
#   6) **جدولُ صلاحيّاتِ كلِّ حدٍّ يُطابِقُ ثابتَ الصلاحيّاتِ في شفرتِه** — لا
#      صلاحيّةٌ مفروضةٌ غيرُ مكتوبةٍ، ولا صلاحيّةٌ مكتوبةٌ غيرُ مفروضةٍ.
#   8) **لا مكتبةَ نداءٍ (axios/undici/…) في package.json بلا إعلانٍ** — وإلّا
#      عمِيَ البابُ 7 بصمتٍ وبقيَ أخضرَ؛ والمُعلَنُ يُوسَّعُ بهِ جردُ البابِ 7.
#   9) **العقدُ المنشورُ لا يُنكِرُ مُصادقةً مفروضةً ولا يدَّعي مُصادقةً غيرَ
#      مفروضةٍ** — وكلُّ حدٍّ يُنكِرُها اليومَ مُدرَجٌ في جردٍ **منتهٍ** بمرجعِ
#      البوّابةِ التي تملكُ العلاجَ (`M1-06`)، فلا يزيدُ الجردُ بصمتٍ ولا يبقى
#      فيه اسمٌ بعدَ أن يُعالَجَ حدُّه.
#
# ولمَ أُضيفَ البابُ 6 (2026-09-13 · المراجعةُ 23/N): انحرافٌ صامتٌ قِيسَ لا
# افتُرِضَ. جدولُ حدِّ التوصيلِ أعلنَ **تسعَ** صلاحيّاتٍ والشفرةُ تفرضُ **إحدى
# عشرةَ** يوماً كاملاً، وجدولُ حدِّ الجغرافيا **لم يوجَدْ أصلاً**: أربعُ صلاحيّاتٍ
# مفروضةٌ منذ 2026-09-07 لا يذكرُها حرفٌ في `docs/`. والأبوابُ 1–5 لم تُخفِقْ لأنّها
# تقرأُ سجلَّ **العملاءِ** لا جدولَ **الصلاحيّاتِ** — فالثغرةُ في غيابِ بابٍ لا في
# كسلِ بابٍ. والمصدرُ الواحدُ للحقيقةِ هوَ **الشفرةُ**، والجدولُ مُشتَقٌّ مُنفَذٌ.
#
# المرجع: docs/07-security/SERVICE_AUTH_ENFORCEMENT.md · ADR-020 · ADR-021 · ADR-022
#
#   bash scripts/checks/validate-service-auth-coverage.sh
#
# لا شبكةَ ولا git: قراءةُ قرصٍ محضةٌ — فلا تخطّيَ له، مرورٌ أو إخفاق.
set -uo pipefail

cd "$(dirname "$0")/../.." || { echo "تعذّر الوصول إلى جذر المستودع" >&2; exit 1; }

RED=$'\033[31m'; GRN=$'\033[32m'; RST=$'\033[0m'

LEDGER="docs/07-security/SERVICE_AUTH_ENFORCEMENT.md"
FAIL=0

ok()   { printf '  %s✓%s %s\n' "$GRN" "$RST" "$1"; }
bad()  { printf '  %s✗%s %s\n' "$RED" "$RST" "$1"; FAIL=1; }

# ── عضويّةٌ حتميّةٌ لا احتماليّة (`RISK-0037`) ───────────────────────────────
# **العيبُ الذي أنشأَ هذهِ الدالّة، مقيساً لا مُستنتَجاً:** كانت كلُّ مقارنةِ
# عضويّةٍ في هذا الحارسِ مكتوبةً `printf '%s\n' "${ARR[@]}" | grep -qxF "$x"`.
# و`grep -q` يخرجُ عندَ **أوّلِ** تطابقٍ فيُغلِقُ الأنبوبَ، فيموتُ `printf`
# بـ`SIGPIPE`، وتحتَ `set -o pipefail` تصيرُ حالةُ الأنبوبِ **141** فيقرأُها
# الشرطُ **«لا تطابق»** — فيُرفَضُ عملٌ صحيحٌ. وهوَ سباقٌ لا خطأُ منطقٍ: يقعُ حينَ
# يسبقُ خروجُ `grep` فراغَ `printf` من الكتابةِ.
#
# **المقيسُ (2026-09-13 · 300 إعادةً مضبوطةً):** 9 رفضاتٍ كاذبةٍ من 300 للمقارنةِ
# **الواحدةِ**، و**0 من 300** بالصيغةِ أدناهُ. وفي التشغيلِ الواحدِ **54 مقارنةً**
# فاحتمالُ إخفاقٍ كاذبٍ ≈**81%** — وقد أخفقَ الحارسُ فعلاً مرّتَينِ متتاليتَينِ
# على شفرةٍ ووثائقَ **لم يتغيَّرْ فيهما حرفٌ** وبأسماءِ صلاحيّاتٍ **مختلفةٍ** في
# كلِّ مرّةٍ (`marketplace:store:review:read` ثمَّ أربعُ صلاحيّاتٍ في أربعِ خدماتٍ).
#
# **ولمَ دالّةٌ واحدةٌ لا سبعُ إصلاحاتٍ موضعيّةٍ:** العيبُ نفسُهُ عُولِجَ وكُتِبَ
# تعليلُهُ حرفاً في `require-doc-update.sh` و`validate-launch-board.sh`، **فعادَ
# في حارسٍ ثالثٍ** لأنَّ العلاجَ كانَ موضعيّاً والنمطُ بقيَ مسموحاً. فالعضويّةُ
# هنا **مصدرُ حقيقةٍ واحدٌ** لا سبعةَ مواضعَ تُصلَحُ واحداً واحداً.
#
# **والخطرُ أخطرُ من إزعاجٍ:** حارسٌ يرفضُ الصحيحَ باحتمالٍ يُعلِّمُ المُشغِّلَ أن
# يُعيدَ التشغيلَ حتّى يخضرَّ — فيصيرُ الرفضُ **الصادقُ** مُعادَ التشغيلِ أيضاً.
# أي أنَّ العيبَ **يُفسِدُ معنى الأحمرِ** لا أنّهُ يُبطئُ دفعةً.
#
# ولا أنبوبَ ولا عمليّةَ فرعيّةَ هنا: مقارنةٌ في الغلافِ نفسِهِ على عنصرٍ عنصرٍ،
# فلا `SIGPIPE` ولا `PIPESTATUS` أصلاً. والمُقارَنةُ **مُطابَقةٌ تامّةٌ** (`=`)
# كما كانَ `grep -qxF` بالضبطِ — لا أوسعَ ولا أضيقَ.
has_exact() { # has_exact <إبرة> [عنصر...]
  local needle="$1"; shift
  local item
  for item in "$@"; do
    [[ "$item" == "$needle" ]] && return 0
  done
  return 1
}

# ── 1) السّجلُّ وصيغتُه ────────────────────────────────────────────────────
if [[ ! -f "$LEDGER" ]]; then
  bad "سجلُّ التغطيةِ مفقودٌ: $LEDGER"
  printf '\n%s✗ حارسُ تغطيةِ هويّةِ الخدمة: إخفاق.%s\n' "$RED" "$RST"
  exit 1
fi
ok "السّجلُّ موجودٌ: $LEDGER"

for marker in "<!-- coverage-ledger:start -->" "<!-- coverage-ledger:end -->"; do
  grep -qF "$marker" "$LEDGER" || bad "علامةُ السّجلِّ مفقودةٌ: $marker"
done

LEDGER_BODY="$(awk '/<!-- coverage-ledger:start -->/{f=1;next}/<!-- coverage-ledger:end -->/{f=0}f' "$LEDGER")"
[[ -n "$LEDGER_BODY" ]] || bad "جسمُ السّجلِّ فارغٌ بين العلامتَين"

# ── 2) كلُّ عميلٍ صادرٍ مذكورٌ ─────────────────────────────────────────────
# العميلُ الصادرُ: services/*/src/infrastructure/http-*.ts — وهو الموضعُ الوحيدُ
# الذي تُبنى فيه نداءاتُ HTTP الخارجةُ في هذا المستودع (ADR-007).
# **وتوسَّعَ البصرُ في 24/N (`RISK-0027`):** كانَ الحارسُ يقرأُ `services/` وحدَها،
# فبقيَ مُنادو الحدودِ في `bots/` **غيرَ مرئيّينَ** له سنةَ عمرِهِ كلَّها؛ وقياسُ
# اليومِ أظهرَ عميلَينِ حقيقيَّينِ بالتسميةِ نفسِها
# (`bots/{customer,driver}-bot/src/infrastructure/http-negotiations.ts`) **لا
# ذِكرَ لهما في السّجلِّ ولا توقيعَ في شفرتِهما** — فدعوى السّجلِّ «أحدَ عشرَ
# موقِّعاً من أحدَ عشرَ عميلاً — لا مؤجَّلَ» كانت صادقةً في `services/` ومُضلِّلةً
# إذا قُرئت دعوى مستودعٍ. والبابُ 7 أدناهُ يُغلِقُ الباقيَ: كلُّ مُنادٍ خامٍ
# أينَما كانَ يُقابَلُ بالسّجلِّ أو باستثناءٍ مُعلَنٍ بسببِه.
mapfile -t CLIENTS < <(ls services/*/src/infrastructure/http-*.ts bots/*/src/infrastructure/http-*.ts 2>/dev/null | sort)
if (( ${#CLIENTS[@]} == 0 )); then
  bad "لم يُعثَر على أيِّ عميلٍ صادرٍ — تغيَّرَ التّرتيبُ، والحارسُ يفحصُ موضعاً لا وجودَ له"
fi

for client in "${CLIENTS[@]}"; do
  if ! grep -qF "$client" <<<"$LEDGER_BODY"; then
    bad "عميلٌ صادرٌ غيرُ مذكورٍ في السّجل: $client"
    printf '      أضِفْ له صفّاً في %s: «موقَّع» إن كان يوقِّع، أو «مؤجَّل» بمرجعِ M1-04.\n' "$LEDGER"
    continue
  fi

  row="$(grep -F "$client" <<<"$LEDGER_BODY" | head -1)"
  # النمطُ `sign…Request` لا `signRequest` حرفاً: منذُ `M1-04` الموجةِ الرابعةِ
  # صارَ العميلُ الذي يُنادي **وجهتَينِ** يحملُ موقِّعاً باسمٍ صريحٍ لكلِّ وجهةٍ
  # (`signOrdersRequest` و`signDispatchRequest`)، لأنّ الجمهورَينِ مختلفانِ.
  # ومطابقةُ الاسمِ الواحدِ حرفاً كانت ستقرأُ عميلاً **يوقِّعُ مرَّتَينِ** غيرَ
  # موقِّعٍ أصلاً — وهذا توسيعُ ما يُقبَلُ في التسميةِ لا تخفيفٌ لما يُشترَط:
  # الشرطُ ما زالَ «أثرُ موقِّعٍ في الشفرةِ»، ومَن لا موقِّعَ له يُرَدُّ كما كان.
  signs=0
  grep -Eq "sign[A-Za-z]*Request" "$client" && signs=1

  if [[ "$row" == *"موقَّع"* ]]; then
    # ── 3) السّجلُّ لا يكذب ────────────────────────────────────────────────
    if (( signs )); then
      ok "موقَّعٌ ومُثبَتٌ في الشفرة: $client"
    else
      bad "السّجلُّ يقول «موقَّع» ولا أثرَ لـsignRequest في الشفرة: $client"
    fi
  elif [[ "$row" == *"مؤجَّل"* ]]; then
    # ── 4) الدَّينُ مُعلَنٌ بمرجعِه ──────────────────────────────────────────
    if [[ "$row" == *"M1-04"* ]]; then
      if (( signs )); then
        bad "السّجلُّ يقول «مؤجَّل» والشفرةُ توقِّعُ فعلاً — السّجلُّ متأخِّرٌ: $client"
      else
        ok "مؤجَّلٌ بإعلانٍ ومرجعٍ (M1-04): $client"
      fi
    else
      bad "صفٌّ «مؤجَّل» بلا مرجعِ بوّابةٍ (M1-04): $client"
    fi
  else
    bad "صفٌّ بلا حالةٍ مقروءةٍ («موقَّع» أو «مؤجَّل»): $client"
  fi
done

# ── 5) الحدُّ المُعلَنُ مفروضاً مفروضٌ فعلاً ───────────────────────────────
# يُقرأُ من السّجلِّ كلُّ سطرٍ يُصرِّحُ بحدٍّ مفروضٍ بالصيغة: `enforced: <خدمة>`
mapfile -t ENFORCED < <(grep -oP '(?<=enforced: )[a-z-]+' <<<"$LEDGER_BODY" | sort -u)
if (( ${#ENFORCED[@]} == 0 )); then
  bad "لا حدَّ مُعلَنٌ مفروضاً في السّجل — دفعةٌ تُدّعي الإنفاذَ ولا تسمّي حدَّها"
fi
for svc in "${ENFORCED[@]}"; do
  app="services/$svc/src/http/app.ts"
  if [[ ! -f "$app" ]]; then
    bad "السّجلُّ يُعلِنُ إنفاذاً في خدمةٍ لا ملفَّ تطبيقٍ لها: $app"
  elif grep -q "registerServiceIdentity" "$app"; then
    ok "الحدُّ مفروضٌ في الشفرة: $app"
  else
    bad "السّجلُّ يُعلِنُ إنفاذاً ولا registerServiceIdentity في: $app"
  fi
done

# ── 6) جدولُ الصلاحيّاتِ يُطابِقُ الشفرةَ ─────────────────────────────────────
# لكلِّ حدٍّ فيه `services/<svc>/src/http/service-identity.ts` بثابتِ صلاحيّاتٍ
# مُصدَّرٍ (`export const <X>_SCOPES = { ... } as const`) يُشترَطُ في السّجلِّ
# كتلةٌ مُعلَّمةٌ `<!-- <svc>-scopes:begin --> … <!-- <svc>-scopes:end -->`
# تذكرُ **كلَّ** صلاحيّةٍ مفروضةٍ **ولا** تذكرُ ما لا تفرضُه الشفرةُ.
# والعلامتانِ شرطٌ لا تزيينٌ: غيابُهما إخفاقٌ لا مرورٌ — فلا تُشترى الخُضرةُ بحذفِ
# الحارسِ. والمطابقةُ على **الأسماءِ** لا على المبرِّراتِ بجانبِها (حدٌّ مُعلَنٌ §6).
# وحارسُ الموضعِ يُربَطُ بالإعلانِ لا بالتخطيطِ العامِّ: كلُّ حدٍّ يقولُ السّجلُّ
# إنّه **مفروضٌ** يُشترَطُ فيه ملفُّ هويّةٍ في موضعِه المُعلَنِ — فنقلُ الملفِّ أو
# إعادةُ تسميتِه تُسقِطُ الفحصَ ولا تُخرِسُه. ولا يُشترَطُ ذلكَ على جذرٍ لا
# يُعلِنُ إنفاذاً أصلاً: الحارسُ لا يخترعُ شرطاً على ما لم يُدَّعَ.
for svc in "${ENFORCED[@]}"; do
  [[ -f "services/$svc/src/http/app.ts" ]] || continue
  if [[ ! -f "services/$svc/src/http/service-identity.ts" ]]; then
    bad "حدٌّ مُعلَنٌ مفروضاً بلا ملفِّ هويّةٍ في موضعِه: services/$svc/src/http/service-identity.ts"
  fi
done

mapfile -t SCOPE_FILES < <(ls services/*/src/http/service-identity.ts 2>/dev/null | sort)
for sfile in "${SCOPE_FILES[@]}"; do
  svc="${sfile#services/}"; svc="${svc%%/*}"

  # صلاحيّاتُ الشفرةِ: القيمُ النصّيّةُ داخلَ ثابتِ الصلاحيّاتِ المُصدَّرِ وحدَه.
  mapfile -t CODE_SCOPES < <(
    awk '/^export const [A-Z_]+_SCOPES = \{/{f=1;next} f&&/^\} as const;/{f=0} f' "$sfile" \
      | grep -oE '"[a-z0-9]+(:[a-z0-9-]+)+"' | tr -d '"' | sort -u
  )
  if (( ${#CODE_SCOPES[@]} == 0 )); then
    ok "لا ثابتَ صلاحيّاتٍ مُصدَّراً في الحدِّ: $svc (لا جدولَ يُطلَبُ منه)"
    continue
  fi

  begin="<!-- ${svc}-scopes:begin -->"; end="<!-- ${svc}-scopes:end -->"
  if ! grep -qF "$begin" "$LEDGER" || ! grep -qF "$end" "$LEDGER"; then
    bad "حدٌّ يفرضُ ${#CODE_SCOPES[@]} صلاحيّةً وجدولُه غيرُ مُعلَّمٍ في السّجل: $svc"
    printf '      أضِفْ في %s كتلةً بين %s و %s.\n' "$LEDGER" "$begin" "$end"
    continue
  fi
  block="$(awk -v b="$begin" -v e="$end" 'index($0,b){f=1;next} index($0,e){f=0} f' "$LEDGER")"
  mapfile -t DOC_SCOPES < <(grep -oE '`[a-z0-9]+(:[a-z0-9-]+)+`' <<<"$block" | tr -d '`' | sort -u)

  missing=(); invented=()
  for s in "${CODE_SCOPES[@]}"; do
    has_exact "$s" "${DOC_SCOPES[@]:-}" || missing+=("$s")
  done
  for s in "${DOC_SCOPES[@]:-}"; do
    [[ -n "$s" ]] || continue
    has_exact "$s" "${CODE_SCOPES[@]}" || invented+=("$s")
  done

  if (( ${#missing[@]} )); then
    bad "صلاحيّةٌ مفروضةٌ في الشفرةِ وغيرُ مكتوبةٍ في جدولِ $svc: ${missing[*]}"
  fi
  if (( ${#invented[@]} )); then
    bad "صلاحيّةٌ في جدولِ $svc لا تفرضُها الشفرةُ: ${invented[*]}"
  fi
  if (( ${#missing[@]} == 0 && ${#invented[@]} == 0 )); then
    ok "جدولُ الصلاحيّاتِ مُطابِقٌ للشفرةِ: $svc (${#CODE_SCOPES[@]} صلاحيّةً)"
  fi
done

# ── 8) قُفلُ أغلفةِ النداءِ: لا مكتبةَ HTTP تدخلُ بلا إعلانٍ ────────────────
# البابُ 7 يقيسُ `fetch(` — وهذا حدُّهُ المُعلَنُ. فلو أُضيفَ `axios` أو `undici`
# غداً لصارَ البابُ 7 أعمى **بصمتٍ** وبقيَ أخضرَ، وهوَ عمىً أسوأُ من عمى
# `RISK-0027` لأنّه يُولَدُ أخضرَ. فيُقفَلُ البابُ هنا **بالرفضِ افتراضاً**: أيُّ
# مكتبةِ نداءٍ في أيِّ `package.json` يجبُ أن تُعلَنَ بسببِها بينَ
# `<!-- http-wrappers:begin/end -->` في السّجلِّ، وحينَ تُعلَنُ يُوسَّعُ جردُ
# البابِ 7 ليشملَ مُستورِديها. وإعلانٌ لمكتبةٍ غيرِ موجودةٍ يُسقِطُ الفحصَ أيضاً:
# الإعلانُ الميتُ يُوسِّعُ الجردَ بلا داعٍ ويُخفي الحقيقةَ كما يُخفيها غيابُه.
HTTP_WRAPPERS=(axios undici got node-fetch ky superagent request phin needle axios-retry request-promise isomorphic-fetch cross-fetch)
HW_BEGIN="<!-- http-wrappers:begin -->"; HW_END="<!-- http-wrappers:end -->"
DECLARED_WRAPPERS=()
if ! grep -qF "$HW_BEGIN" "$LEDGER" || ! grep -qF "$HW_END" "$LEDGER"; then
  bad "كتلةُ أغلفةِ النداءِ المُعلَنةِ مفقودةٌ من السّجلِّ ($HW_BEGIN)"
else
  HW_BLOCK="$(awk -v b="$HW_BEGIN" -v e="$HW_END" 'index($0,b){f=1;next} index($0,e){f=0} f' "$LEDGER")"
  # الإعلانُ يُقرأُ من **الخليّةِ الأولى في صفوفِ الجدولِ** وحدَها، لا من كلِّ
  # ما بينَ العلامتَينِ: نثرُ الكتلةِ يذكرُ أسماءَ المكتباتِ تمثيلاً لا إعلاناً.
  mapfile -t DECLARED_WRAPPERS < <(
    grep -E '^\|' <<<"$HW_BLOCK" \
      | awk -F'|' 'NF>2 {gsub(/^[ \t]+|[ \t]+$/,"",$2); print $2}' \
      | grep -oE '^`[a-z0-9@/._-]+`$' | tr -d '`' | sort -u
  )
  mapfile -t PKG_FILES < <(find . -name package.json -not -path '*/node_modules/*' -not -path './dist/*' | sort)
  FOUND_WRAPPERS=()
  for w in "${HTTP_WRAPPERS[@]}"; do
    for pf in "${PKG_FILES[@]}"; do
      if grep -qE "\"$w\"[[:space:]]*:" "$pf"; then FOUND_WRAPPERS+=("$w"); break; fi
    done
  done
  for w in "${FOUND_WRAPPERS[@]:-}"; do
    [[ -n "$w" ]] || continue
    has_exact "$w" "${DECLARED_WRAPPERS[@]:-}" \
      || bad "مكتبةُ نداءٍ في package.json بلا إعلانٍ في السّجلِّ — البابُ 7 يعمى عنها: $w"
  done
  for w in "${DECLARED_WRAPPERS[@]:-}"; do
    [[ -n "$w" ]] || continue
    has_exact "$w" "${FOUND_WRAPPERS[@]:-}" \
      || bad "إعلانُ غلافِ نداءٍ لا وجودَ له في أيِّ package.json (إعلانٌ ميتٌ): $w"
  done
  ok "قُفلُ أغلفةِ النداءِ: ${#FOUND_WRAPPERS[@]} مكتبةً موجودةً · ${#DECLARED_WRAPPERS[@]} مُعلَنةً (المرجعُ: fetch الأصليُّ وحدَه حينَ يكونُ العددُ صفراً)"
fi

# ── 7) لا مُناديَ خامٍ خارجَ البصرِ (إقفالُ `RISK-0027` بنيويّاً) ─────────────
# البابُ 2 يرى ما يتبعُ التسميةَ `*/src/infrastructure/http-*.ts` وحدَه، فمَن
# نادى حدّاً بـ`fetch(` من ملفٍّ بأيِّ اسمٍ آخرَ كانَ يمرُّ بلا حسابٍ. فيُحصى
# هنا **كلُّ** ملفِّ إنتاجٍ في `services/` و`bots/` و`packages/` فيهِ `fetch(`،
# ويُشترَطُ أن يكونَ إمّا عميلاً مُحصَىً في البابِ 2، أو مذكوراً باستثناءٍ
# مُعلَنٍ بسببِهِ بينَ `<!-- fetch-exceptions:begin/end -->` في السّجلِّ.
# واستثناءٌ لملفٍّ غيرِ موجودٍ يُسقِطُ الفحصَ أيضاً: الاستثناءُ الميتُ يُخفي
# انحرافاً كما يُخفيهِ غيابُ الاستثناءِ.
FE_BEGIN="<!-- fetch-exceptions:begin -->"; FE_END="<!-- fetch-exceptions:end -->"
if ! grep -qF "$FE_BEGIN" "$LEDGER" || ! grep -qF "$FE_END" "$LEDGER"; then
  bad "كتلةُ استثناءاتِ المُنادي الخامِ مفقودةٌ من السّجلِّ ($FE_BEGIN)"
else
  FE_BLOCK="$(awk -v b="$FE_BEGIN" -v e="$FE_END" 'index($0,b){f=1;next} index($0,e){f=0} f' "$LEDGER")"
  mapfile -t FE_PATHS < <(grep -oE '`[A-Za-z0-9_./-]+\.ts`' <<<"$FE_BLOCK" | tr -d '`' | sort -u)

  # 7-أ) الاستثناءُ الميتُ يُسقِط
  for fe in "${FE_PATHS[@]:-}"; do
    [[ -n "$fe" ]] || continue
    [[ -f "$fe" ]] || bad "استثناءٌ مُعلَنٌ لملفٍّ غيرِ موجودٍ (استثناءٌ ميتٌ): $fe"
  done

  # 7-ب) لا يُستثنى عميلٌ حقيقيٌّ من السّجلِّ بحجّةِ الاستثناءِ
  for fe in "${FE_PATHS[@]:-}"; do
    [[ -n "$fe" ]] || continue
    if has_exact "$fe" "${CLIENTS[@]}"; then
      bad "عميلٌ صادرٌ مُدرَجٌ في الاستثناءاتِ — العميلُ يُقابَلُ بالسّجلِّ لا يُستثنى: $fe"
    fi
  done

  # 7-ج) كلُّ مُنادٍ خامٍ: عميلٌ مُحصَىً أو استثناءٌ مُعلَنٌ
  RAW_PATTERN='\bfetch\('
  for w in "${DECLARED_WRAPPERS[@]:-}"; do
    [[ -n "$w" ]] || continue
    RAW_PATTERN="$RAW_PATTERN|from '$w'|from \"$w\"|require\('$w'\)"
  done
  mapfile -t RAW_CALLERS < <(
    grep -rlE "$RAW_PATTERN" services bots packages \
      --include='*.ts' \
      --exclude-dir=node_modules --exclude-dir=dist --exclude-dir=__tests__ \
      --exclude='*.test.ts' 2>/dev/null | sort -u
  )
  if (( ${#RAW_CALLERS[@]} == 0 )); then
    bad "لا مُناديَ خامٍ في المستودعِ كلِّه — تغيَّرَ التّرتيبُ والحارسُ يعدُّ موضعاً لا وجودَ له"
  fi
  unseen=0
  for rc in "${RAW_CALLERS[@]}"; do
    has_exact "$rc" "${CLIENTS[@]}" && continue
    has_exact "$rc" "${FE_PATHS[@]:-}" && continue
    bad "مُنادٍ خامٌ خارجَ بصرِ السّجلِّ: $rc"
    printf '      إمّا أن يُسمّى عميلاً في %s، أو يُعلَنَ استثناءً بسببِه بينَ العلامتَينِ.\n' "$LEDGER"
    unseen=1
  done
  (( unseen )) || ok "لا مُناديَ خامٍ خارجَ البصرِ: ${#RAW_CALLERS[@]} ملفّاً (${#CLIENTS[@]} عميلاً + ${#FE_PATHS[@]} استثناءً مُعلَناً)"
fi

# ── 9) العقدُ المنشورُ لا يكذبُ على مُصادقةٍ مفروضةٍ ────────────────────
# **العطبُ الذي أنشأَ هذا البابَ، مقيساً لا مُقدَّراً (2026-09-14):** ثمانيةُ
# حدودٍ تفرضُ هويّةَ الخدمةِ فعلاً (`registerServiceIdentity` في شفرتِها،
# وثمانونَ مساراً مفروضاً منها **خمسةٌ وسبعونَ عمليّةً منشورةً** تُرفَضُ
# بـ`401` بلا توقيعٍ، وأربعٌ وستّونَ صلاحيّةً مُصدَّرةً)،
# و**لا عقدَ منشورَ واحدٌ من أربعةَ عشرَ** في `services/*/contracts/api.openapi.yml`
# يذكرُ `securitySchemes` ولا `security:` ولا `401`. فالعقدُ المنشورُ **ينفي
# بالسكوتِ مُصادقةً مفروضةً**، ومُوَلِّدُ عميلٍ يقرأُهُ يُنتِجُ نداءاً غيرَ
# موقَّعٍ يُردُّ دائماً. وهذا الدَّينُ **مُعلَنٌ من قبلُ** في §2.7 وفي
# `services/delivery/src/http/service-identity.ts`، وعلاجُهُ مملوكٌ لبوّابةٍ
# أخرى (`M1-06` — وهي موقوفةٌ على `M1-05`)، فلا يجوزُ لهذا الحارسِ أن يدَّعي
# إصلاحَه. **ويجوزُ لهُ واحدٌ وهو المقصودُ هنا: أن يمنعَ الدَّينَ من أن
# ينموَ بصمتٍ، وأن يمنعَ العكسَ وهو أخطرُ: عقدٌ يدَّعي مُصادقةً لا إنفاذَ
# لها في الشفرةِ.**
#
# ولمَ جردٌ مُعلَنٌ لا رفضٌ فوريٌّ: الرفضُ الفوريُّ يُخفِقُ على الثمانيةِ جميعاً
# في أوّلِ تشغيلٍ، فيصيرُ الأحمرُ حالةَ المستودعِ الدائمةَ فيفقدُ معناهُ — وهو
# بالضبطِ ما تمنعُهُ قاعدةُ «لا تعطّلِ البوّابةَ ولا تُفرِّغِ الأحمرَ من معناه».
# فالمقيسُ يُحَوَّلُ إلى **جردٍ منتهٍ مكتوبٍ** يُقرَأُ من السّجلِّ، والحارسُ
# يرفضُ ثلاثةً: حدّاً جديداً يُفرَضُ ولا يُعلِنُ عقدُه (**الدَّينُ لا ينمو**)،
# واسماً في الجردِ صارَ عقدُه مُعلِناً أو لم يعدِ مفروضاً (**الجردُ لا يكذبُ
# ولا يتقادمُ**)، وعقداً يُعلِنُ مُصادقةً ولا إنفاذَ لها (**لا وعدَ أمنٍ
# كاذباً**). واسمُ الترويسةِ يُقرَأُ من الشفرةِ لا يُكتَبُ هنا: مصدرُ حقيقةٍ
# واحدٌ، فعقدٌ يُعلِنُ ترويسةً غيرَ المفروضةِ يُرَدُّ.
CAD_BEGIN="<!-- contract-auth-debt:begin -->"; CAD_END="<!-- contract-auth-debt:end -->"
HEADER_SRC="packages/service-auth/src/http.ts"
AUTH_HEADER=""
if [[ -f "$HEADER_SRC" ]]; then
  AUTH_HEADER="$(grep -oE 'SERVICE_AUTH_HEADER = "[a-z0-9-]+"' "$HEADER_SRC" | head -1 | grep -oE '"[a-z0-9-]+"' | tr -d '"')"
fi
if [[ -z "$AUTH_HEADER" ]]; then
  bad "تعذَّرَ قراءةُ اسمِ ترويسةِ الهويّةِ من الشفرةِ — البابُ 9 يقيسُ موضعاً لا وجودَ له: $HEADER_SRC"
fi

DEBT_SERVICES=()
if ! grep -qF "$CAD_BEGIN" "$LEDGER" || ! grep -qF "$CAD_END" "$LEDGER"; then
  bad "كتلةُ جردِ دَينِ العقدِ المنشورِ مفقودةٌ من السّجلِّ ($CAD_BEGIN)"
else
  CAD_BLOCK="$(awk -v b="$CAD_BEGIN" -v e="$CAD_END" 'index($0,b){f=1;next} index($0,e){f=0} f' "$LEDGER")"
  # الإعلانُ يُقرَأُ من **الخليّةِ الأولى في صفوفِ الجدولِ** وحدَها
  # (كالبابِ 8)، فنثرُ الكتلةِ يذكرُ أسماءَ الحدودِ تمثيلاً لا إعلاناً.
  mapfile -t DEBT_SERVICES < <(
    grep -E '^\|' <<<"$CAD_BLOCK" \
      | awk -F'|' 'NF>2 {gsub(/^[ \t]+|[ \t]+$/,"",$2); print $2}' \
      | grep -oE '^`[a-z-]+`$' | tr -d '`' | sort -u
  )
  # 9-أ) كلُّ صفٍ في الجردِ يحملُ مرجعَ البوّابةِ التي تملكُ العلاجَ
  for svc in "${DEBT_SERVICES[@]:-}"; do
    [[ -n "$svc" ]] || continue
    row="$(grep -E '^\|' <<<"$CAD_BLOCK" | grep -F "\`$svc\`" | head -1)"
    [[ "$row" == *"M1-06"* ]] \
      || bad "صفُّ دَينٍ في الجردِ بلا مرجعِ البوّابةِ المالكةِ (M1-06): $svc"
  done
fi

# 9-ب) كلُّ حدٍّ مفروضٍ: عقدٌ يُعلِنُ، أو اسمٌ في الجردِ — ولا ثالثَ
for svc in "${ENFORCED[@]}"; do
  contract="services/$svc/contracts/api.openapi.yml"
  if [[ ! -f "$contract" ]]; then
    bad "حدٌّ مفروضٌ بلا عقدٍ منشورٍ في موضعِه: $contract"
    continue
  fi
  if grep -q "securitySchemes" "$contract"; then
    # العقدُ يُعلِنُ — فلا يجوزُ أن يبقى في جردِ الدَّينِ (إعلانٌ ميتٌ)،
    # ويجبُ أن يذكرَ الترويسةَ المفروضةَ نفسَها حرفاً.
    if has_exact "$svc" "${DEBT_SERVICES[@]:-}"; then
      bad "عقدٌ يُعلِنُ المُصادقةَ واسمُهُ باقٍ في جردِ الدَّينِ (إعلانٌ ميتٌ): $svc"
    fi
    if [[ -n "$AUTH_HEADER" ]] && ! grep -qF "$AUTH_HEADER" "$contract"; then
      bad "عقدٌ يُعلِنُ مُصادقةً بترويسةٍ غيرِ المفروضةِ ($AUTH_HEADER مفقودةٌ): $contract"
    else
      ok "العقدُ المنشورُ يُعلِنُ المُصادقةَ المفروضةَ: $svc"
    fi
  else
    if has_exact "$svc" "${DEBT_SERVICES[@]:-}"; then
      ok "دَينٌ مُعلَنٌ بمرجعِه (M1-06) — العقدُ لا يُعلِنُ والحدُّ مفروضٌ: $svc"
    else
      bad "حدٌّ مفروضٌ وعقدُهُ المنشورُ ينفي المُصادقةَ بلا إعلانٍ في الجرد: $svc"
      printf '      أضِفْ `securitySchemes` في %s أو صفّاً للحدِّ بينَ علامتَي %s بمرجعِ M1-06.\n' "$contract" "$CAD_BEGIN"
    fi
  fi
done

# 9-ج) اسمٌ في الجردِ لحدٍّ غيرِ مفروضٍ — جردٌ متقادمٌ يُوهِمُ بحراسةٍ
for svc in "${DEBT_SERVICES[@]:-}"; do
  [[ -n "$svc" ]] || continue
  has_exact "$svc" "${ENFORCED[@]}" \
    || bad "اسمٌ في جردِ دَينِ العقدِ لحدٍّ لا يُعلِنُ السّجلُّ إنفاذَه (جردٌ متقادمٌ): $svc"
done

# 9-د) الاتّجاهُ الأخطرُ: عقدٌ يدَّعي مُصادقةً ولا إنفاذَ لها في الشفرةِ.
# ولا استثناءَ له ولا جردَ: وعدُ أمنٍ كاذبٌ أسوأُ من سكوتٍ مُعلَنٍ، لأنَّ مُوَلِّدَ
# عميلٍ يقرأُهُ يُرسِلُ سرّاً إلى حدٍّ لا يتحقّقُ منهُ أصلاً.
#
# **وما لا يُدَّعى:** المقيسُ اليومَ أنَّ لا عقدَ واحدٌ يُعلِنُ أيَّ `securitySchemes`،
# فهذا البابُ **لا يُميِّزُ** بينَ مُصادقةِ خدمةٍ ومُصادقةِ مستخدمٍ نهائيٍّ. فإذا
# جاءَ يوماً حدٌّ يُعلِنُ في عقدِهِ مُصادقةَ مستخدمٍ مشروعةً (`M1-02`) وهوَ غيرُ
# مفروضٍ لهويّةِ الخدمةِ، فالطريقُ **توسيعُ هذا البابِ بقرارٍ مكتوبٍ** لا تخطّيه:
# الرفضُ افتراضاً مقصودٌ، والتمييزُ يُضافُ حينَ يوجدُ محلُّهُ لا قبلَه.
mapfile -t ALL_CONTRACTS < <(ls services/*/contracts/api.openapi.yml 2>/dev/null | sort)
for contract in "${ALL_CONTRACTS[@]:-}"; do
  [[ -n "$contract" ]] || continue
  svc="${contract#services/}"; svc="${svc%%/*}"
  has_exact "$svc" "${ENFORCED[@]}" && continue
  if grep -q "securitySchemes" "$contract"; then
    bad "عقدٌ يدَّعي مُصادقةً ولا إنفاذَ لها في شفرةِ حدِّه: $contract"
  fi
done

if (( FAIL )); then
  printf '\n%s✗ حارسُ تغطيةِ هويّةِ الخدمة: إخفاق. الدفعُ مرفوض.%s\n' "$RED" "$RST"
  printf '  اقرأ: %s · docs/12-testing/M1-03_GATE.md\n' "$LEDGER"
  exit 1
fi

printf '\n%s✓ حارسُ تغطيةِ هويّةِ الخدمة: كلُّ عميلٍ مُعلَنٌ بصدقٍ، والحدُّ المُعلَنُ مفروضٌ.%s\n' "$GRN" "$RST"
printf '  والتغطيةُ الكاملةُ ليست مُدَّعاةً هنا: بوّابةُ M1-04 المستقلّة.\n'
exit 0
