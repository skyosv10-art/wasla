#!/usr/bin/env bash
# validate-test-invocation.sh — حارسُ **مصدرِ الاستدعاءِ الواحدِ** للاختباراتِ. (M0-35)
#
# ── العطبُ المحروسُ ───────────────────────────────────────────────────────
# `pnpm -r test` يُشغِّلُ الحزمَ بتوازٍ افتراضيٍّ، و**إحدى عشرةَ حزمةَ بوّاباتٍ**
# تملكُ مخطَّطاتِها على **القاعدةِ نفسِها** وتُسقِطُها وتُعيدُ بناءَها في
# `beforeAll`. ثلاثٌ منها تملكُ مخطَّطَ السوقِ بعينِه، فقِيسَ إخفاقُ **3 من 3**
# متوازياً ونجاحُ **3 من 3** مُسلسَلاً — على `main` نفسِهِ (المراجعةُ 40/N §5).
# فصارَ `scripts/run-tests.sh` مصدرَ الاستدعاءِ الواحدَ، وهذا الحارسُ يمنعُ
# انحلالَهُ.
#
# ── أربعُ حُجَجٍ يُثبِتُها ─────────────────────────────────────────────────
# 1) **لا استدعاءَ ثانياً:** لا `pnpm -r … test` تنفيذيّاً في أيِّ سيرٍ أو سكربتٍ
#    أو `package.json` إلّا داخلَ المُشغِّلِ. ثلاثُ نسخٍ من سطرٍ واحدٍ تعني أنَّ
#    إصلاحاً في واحدةٍ يتركُ اثنتَينِ مُعطوبتَينِ، **فيُخالِفُ المحليُّ CI** فيصيرُ
#    الفرقُ عذراً يُقالُ في المراجعةِ («يمرُّ عندي»).
# 2) **لا حزمةَ تسقطُ:** اتّحادُ شِقَّي المُشغِّلِ = كلُّ حزمةٍ لها `test` **مقيساً
#    من القرصِ استقلالاً**، والشِّقّانِ **منفصلانِ**. وهوَ عينُ العطبِ الذي أُصلِحَ
#    في `validate-launch-board.sh` قبلَ يومٍ: صفوفٌ تسقطُ صامتةً والحارسُ أخضرُ.
# 3) **كلُّ مالكِ مخطَّطٍ مُسلسَلٌ:** كلُّ حزمةٍ يصلُ **إغلاقُ استيرادِ** اختبارِها
#    الافتراضيِّ إلى تنفيذِ DDL على مُشغِّلٍ حقيقيٍّ تقعُ في الشِّقِّ المُسلسَلِ.
# 4) **المُرشِّحاتُ تُطابِقُ المُشتَقَّ بعينِهِ (M0-42):** مُرشِّحٌ لا يُطابِقُ
#    حزمةً كانَ يُنتِجُ خضرةً صامتةً (`No projects matched the filters` يخرجُ
#    0) — فصارَ عدمُ المطابقةِ إخفاقاً صريحاً.
#
# ── ولماذا معيارٌ **مختلفٌ** عن معيارِ المُشغِّلِ ───────────────────────────
# المُشغِّلُ يشتقُّ من **إعدادِ vitest**. وهذا الحارسُ يقيسُ من **إغلاقِ الاستيرادِ
# ونصِّ الشفرةِ**. ولو أعادَ الحارسُ اشتقاقَ المُشغِّلِ لكانَ **يُصادِقُ على
# نفسِهِ**: منطقٌ واحدٌ يُقاسُ بنفسِهِ يمرُّ دائماً ولو كانَ خطأً. فالمعيارانِ
# اثنانِ، والخُلْفُ بينَهُما إخفاقٌ مقروءٌ لا تفصيلٌ داخليٌّ.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

GRN=$'\033[32m'; RED=$'\033[31m'; DIM=$'\033[2m'; RST=$'\033[0m'
FAIL=0
fail() { printf '%s✗%s %s\n' "$RED" "$RST" "$1" >&2; FAIL=1; }

RUNNER="scripts/run-tests.sh"
[[ -f "$RUNNER" ]] || { fail "$RUNNER غائبٌ — لا مصدرَ استدعاءٍ."; exit 1; }

# ── 1) لا استدعاءَ ثانياً ─────────────────────────────────────────────────
# يُفتَّشُ عن **صيغةِ الاستدعاءِ** لا عن ذكرِ العبارةِ: سطرٌ يبدأُ بـ`pnpm` (أو
# `- pnpm` في YAML أو `run: pnpm`) ويحملُ `-r`/`--recursive` ثمَّ `test`. ولمَ
# الصيغةُ لا العبارةُ؟ لأنَّ المستودعَ يذكرُ `pnpm -r test` في عشراتِ التعليقاتِ
# وفي نصِّ رسالةِ حارسٍ آخرَ — ومنعُ **ذكرِ** العطبِ كانَ سيُعاقِبَ التوثيقَ ويُخفيَ
# الشرحَ، وذاكَ ثمنٌ بلا مقابلٍ. والاستثناءُ بالمِلفِّ للمُشغِّلِ ولهذا الحارسِ
# ولسويداءِ الحوكمةِ (تحملُ الصيغةَ عيّنةً بقصدٍ).
# و`--hidden` **لازمٌ لا تجميلٌ**: `.github/workflows/` و`.gitlab-ci.yml` يبدآنِ
# بنقطةٍ، و`rg` يتخطّى المخفيَّ افتراضيّاً — فكانَ الحارسُ **يعمى عن خطَّي CI
# كلَّيهِما**، أي عن الموضعِ الأوّلِ الذي يُكرَّرُ فيهِ الاستدعاءُ. كشفَتْهُ حالةُ
# حوكمةٍ (8) لا مراجعةٌ بالعينِ.
# و**لا `rg` في مسارِ الثقةِ**: كانَ المسحُ `rg … 2>/dev/null || true`، و`rg` غيرُ
# مُثبَّتٍ على عاملِ GitHub — فكانَ «الأمرُ غيرُ موجودٍ» يُبتلَعُ فتخرجُ القائمةُ
# فارغةً **فيمرُّ هذا البابُ أخضرَ على لا شيءٍ**. كشفَهُ أوّلُ حكمٍ حقيقيٍّ من CI
# (سيرُ 34873584143): حالةُ الطفرةِ (8) «متوقع fail وجاء pass» في CI وهيَ خضراءُ
# محلّيّاً — أي مُحلّيٌّ يُخالِفُ CI، وهوَ عينُ ما أُنشئَ هذا الحارسُ لمنعِهِ.
# فصارَ المسحُ بـ`python3` (شرطُ تشغيلِ البوّابةِ أصلاً) في المِلفِّ نفسِهِ الذي
# يمسحُ `package.json` — مصدرُ حقيقةٍ واحدٌ، وأداةٌ ثالثةٌ أقلُّ.
SCAN_RC=0
OFFENDERS="$(python3 scripts/checks/lib/audit_test_invocation.py --scan-lines "$ROOT")" || SCAN_RC=$?
(( SCAN_RC == 0 )) || fail "مَسحُ صيغةِ الاستدعاءِ أخفقَ (rc=$SCAN_RC) — ولا يُقرأُ العُطلُ نجاحاً."
JSON_OFFENDERS="$(python3 scripts/checks/lib/audit_test_invocation.py --scan-scripts "$ROOT" || true)"
if [[ -n "$JSON_OFFENDERS" ]]; then
  OFFENDERS="${OFFENDERS:+$OFFENDERS$'\n'}$JSON_OFFENDERS"
fi

if [[ -n "$OFFENDERS" ]]; then
  fail "استدعاءٌ ثانٍ للاختباراتِ خارجَ \`$RUNNER\` — والنسخُ تتباعدُ فيُخالِفُ المحليُّ CI:"
  printf '%s%s%s\n' "$DIM" "$OFFENDERS" "$RST" >&2
fi

# ── 4) مُرشِّحاتُ المُشغِّلِ تُطابِقُ المُشتَقَّ بعينِهِ (M0-42) ─────────────
# قِيسَ أنَّ `pnpm -r --filter ./لا-شيء test` يخرجُ **0** — فمُرشِّحٌ لا
# يُطابِقُ كانَ يُنتِجُ خضرةً صامتةً في الشِّقِّ كلِّهِ. فالمُشغِّلُ صارَ
# يُثبِتُ ذلكَ بنمطِ `--verify-filters` (مطابقةُ مجموعتَينِ بلا تشغيلِ
# اختبارٍ)، وهذا الحارسُ يقرأُ حكمَهُ ولا يُعيدُ بناءَهُ — فلا يُصادِقُ
# المُشتَقُّ على نفسِهِ، ووسمُ الخِتامِ `FILTERS\tOK` إلزاميٌّ: خرجٌ بلا
# وسمٍ مقطوعٌ ولا يُقرأُ نجاحاً.
VF_OUT="$(bash "$RUNNER" --verify-filters 2>&1)"
VF_RC=$?
if (( VF_RC != 0 )) || ! grep -q "FILTERS$(printf '\t')OK" <<< "$VF_OUT"; then
  fail "مُرشِّحاتُ المُشغِّلِ لا تُطابِقُ المُشتَقَّ من القرصِ (rc=$VF_RC) — ولا تُقبَلُ خضرةٌ صامتةٌ:"
  printf '%s%s%s\n' "$DIM" "$VF_OUT" "$RST" >&2
fi

# ── 2 و3) اكتمالُ الشِّقَّينِ وانفصالُهُما، وتسلسلُ كلِّ مالكِ مخطَّطٍ ────────
GROUPS_OUT="$(bash "$RUNNER" --print-groups 2>&1)"
RC=$?
if (( RC != 0 )); then
  fail "\`$RUNNER --print-groups\` أخفقَ (rc=$RC) — ولا يُقرأُ العُطلُ نجاحاً:"
  printf '%s%s%s\n' "$DIM" "$GROUPS_OUT" "$RST" >&2
else
  # (M0-42) لا `|| true` هنا بعدَ اليومِ: قِيسَ في CI ([35046705655]) أنَّ
  # عُطلَ المُدقِّقِ (بلا `pnpm`) كانَ **يُبتلَعُ** فيُمرُّ البابُ أخضرَ على
  # لا شيءِ — فالحكمُ الأحمرُ للمُدقِّقِ **إخفاقٌ مقروءٌ** لا عُطلٌ يُهملُ.
  AUDIT_RC=0
  REPORT="$(printf '%s\n' "$GROUPS_OUT" \
    | python3 scripts/checks/lib/audit_test_invocation.py --audit-groups "$ROOT")" || AUDIT_RC=$?
  if (( AUDIT_RC != 0 )); then
    fail "المُدقِّقُ نفسُهُ أخفقَ (rc=$AUDIT_RC) — ولا يُقرأُ العُطلُ نجاحاً:"
    printf '%s%s%s\n' "$DIM" "$REPORT" "$RST" >&2
  elif [[ -n "$REPORT" ]]; then
    while IFS= read -r line; do [[ -n "$line" ]] && fail "$line"; done <<< "$REPORT"
  fi
fi

if (( FAIL == 0 )); then
  N_PAR="$(grep -c '^PARALLEL' <<< "$GROUPS_OUT")"
  N_SER="$(grep -c '^SERIAL' <<< "$GROUPS_OUT")"
  printf '%s✓%s استدعاءُ الاختباراتِ: مصدرٌ واحدٌ · %s حزمةً متوازيةً · %s حزمةَ بوّاباتٍ مُسلسَلةً · لا حزمةَ ساقطةً · مُرشِّحاتٌ مُطابِقةٌ.\n' \
    "$GRN" "$RST" "$N_PAR" "$N_SER"
fi
exit "$FAIL"
