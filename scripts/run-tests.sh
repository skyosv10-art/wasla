#!/usr/bin/env bash
# run-tests.sh — **مصدرُ استدعاءٍ واحدٌ** لحزمةِ الاختباراتِ في المستودعِ. (M0-35)
#
#   bash scripts/run-tests.sh              # الشِّقَّانِ: المتوازي ثمَّ المُسلسَلُ
#   bash scripts/run-tests.sh --print-groups   # يطبعُ الشِّقَّينِ ولا يُشغِّلُ شيئاً
#
# ── لماذا يوجد هذا السكربت ────────────────────────────────────────────────
# `pnpm -r test` يُشغِّلُ الحزمَ **بتوازٍ افتراضيٍّ** (`--workspace-concurrency`،
# قيمتُها الافتراضيّةُ 4). و**إحدى عشرةَ حزمةَ بوّاباتٍ** (`packages/*-e2e`) تملكُ
# مخطَّطَ خدمتِها على **القاعدةِ نفسِها** (`DATABASE_URL` واحدٌ) وتُسقِطُهُ وتُعيدُ
# بناءَهُ في `beforeAll`. وثلاثٌ منها تملكُ **مخطَّطَ السوقِ بعينِه**
# (`delivery-e2e` · `marketplace-e2e` · `search-e2e`) — فإحداهُنَّ تُسقِطُ جداولَ
# الأخرى **وهيَ تعملُ**.
#
# ── القياسُ الذي أنشأَ هذا الملفَّ (2026-09-14 · المراجعةُ 40/N) ─────────────
# تشغيلُ الثلاثِ معاً بلا تسلسلٍ أخفقَ **3 من 3**:
#     duplicate key value violates unique constraint "pg_type_typname_nsp_index"
#     relation "marketplace_outbox" does not exist
# وبـ`--workspace-concurrency=1` نجحَ **3 من 3**. والعطبُ قِيسَ **على شجرةِ عملٍ
# منفصلةٍ من `main`** فأخفقَ 3 من 3 كذلك — فليسَ انحداراً أحدثَتْهُ دفعةٌ بعينِها،
# بل شرطُ عزلٍ **غائبٌ من الاستدعاءِ**.
#
# ── لماذا لا يُقالُ «تقلُّبٌ يُعادُ تشغيلُهُ» ───────────────────────────────
# لأنَّ المُصابَ **بوّابةُ خروجِ طورٍ**. وبوّابةٌ تتقلّبُ **بوّابةٌ تُعادُ حتّى
# تخضرَّ** — فتصيرُ الخضرةُ حظّاً لا شهادةً، وذاكَ أخطرُ من بوّابةٍ حمراءَ:
# الحمراءُ تُقرأُ حكماً، والمتقلّبةُ تُقرأُ إزعاجاً فتُهمَلُ ثمَّ تُسكَتُ.
#
# ── ولماذا لم يكفِ الحارسُ القائمُ ─────────────────────────────────────────
# `validate-integration-isolation.sh` يحرسُ التوازيَ **داخلَ الحزمةِ**
# (`fileParallelism`) — وهوَ بابٌ آخرُ. ولا يرى التوازيَ **بينَ الحزمِ** بقصدِ
# تصميمِهِ، وقد صرَّحَ بذلكَ في حدِّهِ المُعلَنِ. فالبابانِ اثنانِ ولكلٍّ حارسُهُ.
#
# ── القرارُ: تسلسلٌ للبوّاباتِ وحدَها، لا للمستودعِ كلِّهِ ──────────────────
# `--workspace-concurrency=1` على الشجرةِ كلِّها كانَ سيُطيلَ التحقّقَ بلا سببٍ:
# الحزمُ التي لا تمسُّ قاعدةً لا تتسابقُ. فالشِّقَّانِ:
#   • **المتوازي:** كلُّ حزمةٍ فيها `test` وليست بوّابةً — بالتوازي الافتراضيِّ.
#   • **المُسلسَلُ:** حزمُ البوّاباتِ — `--workspace-concurrency=1`.
# **ولا اختبارَ يُستثنى ولا يُتخطّى ولا تُخفَّفُ عتبةٌ** — يتغيَّرُ **ترتيبُ**
# التشغيلِ لا **مجموعتُهُ**. وذاكَ ما يُثبِتُهُ
# `scripts/checks/validate-test-invocation.sh`: اتّحادُ الشِّقَّينِ = كلُّ حزمةٍ
# لها `test` **مقيساً من القرصِ**، فلا حزمةَ تسقطُ صامتةً — وهوَ عينُ العطبِ
# الذي أُصلِحَ في `validate-launch-board.sh` قبلَ يومٍ.
#
# ── لماذا سكربتٌ واحدٌ لا سطرٌ مُكرَّرٌ في ثلاثةِ أماكنَ ────────────────────
# `scripts/verify.sh` و`.github/workflows/ci.yml` و`.gitlab-ci.yml` كانت تُكرِّرُ
# `pnpm -r test`. وثلاثةُ نسخٍ تعني أنَّ إصلاحاً في واحدةٍ يتركُ اثنتَينِ
# مُعطوبتَينِ — و**المحليُّ يُخالِفُ CI** فيصيرُ الفرقُ سبباً يُقالُ في المراجعةِ
# («يمرُّ عندي»). فصارَ الاستدعاءُ **مصدرَ حقيقةٍ واحداً**، وحرسٌ يمنعُ عودةَ
# `pnpm -r … test` مباشرةً إلى أيِّ سيرٍ أو سكربتٍ.
#
# ── الحدُّ المُعلَنُ ───────────────────────────────────────────────────────
# هذا يرفعُ سباقَ **الحزمِ** على قاعدةٍ واحدةٍ. ولا يُدَّعى أنَّهُ يرفعُ كلَّ
# سباقٍ: مُشغِّلانِ متزامنانِ على **الآلةِ نفسِها** (مُطوِّرٌ يُشغِّلُ بوّابةً
# ويداً واحدةً في آنٍ) يتسابقانِ كما كانا، لأنَّ التسلسلَ هنا داخلَ العمليّةِ
# الواحدةِ لا قفلٌ على القاعدةِ. والحلُّ الجذريُّ لذلكَ **قاعدةٌ لكلِّ حزمةٍ** أو
# `schema-per-worker`، وهوَ نطاقٌ مستقلٌّ. ولا يُدَّعى أثرٌ في CI اليومَ: لا
# `DATABASE_URL` هناكَ فالبوّاباتُ تتخطّى نفسَها — الأثرُ محليٌّ حيثُ تُقاسُ
# البوّاباتُ فعلاً، وهوَ حيثُ كانَ يُقرأُ الحكمُ.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

GRN=$'\033[32m'; RED=$'\033[31m'; DIM=$'\033[2m'; BLD=$'\033[1m'; RST=$'\033[0m'

# ── اشتقاقُ الشِّقَّينِ من القرصِ — لا قائمةَ يدٍ تصدأُ ────────────────────
# المعيارُ ولمَ هوَ هوَ: انظر `scripts/checks/lib/test_groups.py`. وهوَ ملفٌّ
# مستقلٌّ لا سطرٌ مضمَّنٌ هنا، لأنَّ حارسَ الاستدعاءِ يقرأُ **خَرْجَ هذا السكربتِ**
# (`--print-groups`) لا الاشتقاقَ نفسَهُ — فلا يُصادِقُ الاشتقاقُ على نفسِهِ.
GROUPS_FILE="$(mktemp)"
trap 'rm -f "$GROUPS_FILE"' EXIT
python3 scripts/checks/lib/test_groups.py "$ROOT" > "$GROUPS_FILE"
DERIVE_RC=$?

# وسمُ خِتامٍ إلزاميٌّ: غيابُهُ إخفاقٌ لا نجاحٌ — فمُشتَقٌّ نصفُهُ ناقصٌ كانَ
# سيُنتِجُ شِقّاً ناقصاً **فتسقطُ حزمٌ من الاختبارِ صامتةً** وهيَ العلّةُ نفسُها
# التي يُحاكمُها هذا الملفُّ. ولا `grep -q` بعدَ أنبوبٍ (`RISK-0037`).
if (( DERIVE_RC != 0 )) || ! grep -q "^OK$(printf '\t')" "$GROUPS_FILE"; then
  printf '%s✗ لم يكتمل اشتقاقُ الشِّقَّينِ — ولا يُقرأُ العُطلُ نجاحاً:%s %s\n' \
    "$RED" "$RST" "$(sed -n 's/^FATAL\t//p' "$GROUPS_FILE")" >&2
  exit 1
fi

PAR=(); GATE=()
while IFS=$'\t' read -r kind path; do
  case "$kind" in
    PARALLEL) PAR+=("$path") ;;
    SERIAL)   GATE+=("$path") ;;
  esac
done < "$GROUPS_FILE"

if [[ "${1:-}" == "--print-groups" ]]; then
  # صيغةٌ يقرأُها الحارسُ حرفاً — لا يُعيدُ اشتقاقَها بنفسِهِ فيُصادِقَ على نفسِهِ.
  for p in "${PAR[@]}";  do printf 'PARALLEL\t%s\n' "$p"; done
  for p in "${GATE[@]}"; do printf 'SERIAL\t%s\n' "$p"; done
  # وسمُ خِتامٍ: يقرؤهُ الحارسُ ليُميِّزَ خَرْجاً **تامّاً** من خَرْجٍ مقطوعٍ. وبلا
  # وسمٍ كانَ أنبوبٌ يُقطَعُ في منتصفِهِ يُنتِجُ «صفرَ خُلْفٍ» فحارساً أخضرَ.
  printf 'OK\t%s\n' "$(( ${#PAR[@]} + ${#GATE[@]} ))"
  exit 0
fi


if (( ${#GATE[@]} == 0 )); then
  printf '%s✗ صفرُ حزمِ بوّاباتٍ — والمستودعُ فيهِ إحدى عشرةَ: الاشتقاقُ معطوبٌ.%s\n' \
    "$RED" "$RST" >&2
  exit 1
fi

# ── بابُ المُرشِّحِ الفارغِ (M0-42) ──────────────────────────────────────────
# قِيسَ (وثيقةُ دليلِ M0-42 · الحالةُ ج) أنَّ `pnpm -r --filter ./لا-شيء test`
# يخرجُ **0** برسالةِ «No projects matched the filters» — أي أنَّ مُرشِّحاً لا
# يُطابِقُ حزمةً كانَ يُنتِجُ **خضرةً صامتةً**: ينجرفُ اسمُ حزمةٍ أو يزولُ،
# فتسقطُ من التشغيلِ والبوّابةُ خضراءُ. فصارَ كلُّ شِقٍّ يُثبِتُ **بعددٍ
# مقيسٍ** أنَّ مُرشِّحاتِهِ طابقتْ كلَّ ما اشتُقَّ من القرصِ — وعدمُ
# المطابقةِ إخفاقٌ صريحٌ لا سكوتًا أخضرَ.
_assert_filter_coverage() { # <اسمُ-مصفوفةِ-المسارات> <اسمُ الشِّقِّ>
  # مطابقةُ **مجموعتَينِ** لا عدِّ نجاحاتٍ: ما طابقتْهُ المُرشِّحاتُ يجبُ أن
  # يكونَ المُشتَقَّ من القرصِ **بعينِهِ** — لا زائدَ عليهِ ولا ناقصَ عنهُ.
  # ونداءُ `pnpm list` واحدٌ للشِّقِّ كلِّهِ لا نداءٌ لكلِّ حزمةٍ.
  local -n _paths="$1"; local _leg="$2"
  (( ${#_paths[@]} > 0 )) || return 0
  local _filters=() _p _got _expected _diff
  for _p in "${_paths[@]}"; do _filters+=("--filter=./$_p"); done
  _expected="$(printf '%s\n' "${_paths[@]}" | sort)"
  _got="$(pnpm -r "${_filters[@]}" list --depth -1 --parseable 2>/dev/null \
    | sed "s|^$ROOT/||" | sort)" || true
  if [[ -z "$_got" ]]; then
    printf '%s✗ الشِّقُّ %s: `pnpm list` لم يُخرِجْ شيئاً — لا يُقرأُ العُطلُ نجاحاً.%s\n' "$RED" "$_leg" "$RST" >&2
    return 1
  fi
  _diff="$(comm -3 <(printf '%s\n' "$_expected") <(printf '%s\n' "$_got"))"
  if [[ -n "$_diff" ]]; then
    printf '%s✗ الشِّقُّ %s: المُرشِّحاتُ لا تُطابِقُ المُشتَقَّ من القرصِ — خضرةٌ صامتةٌ لا تُقبَلُ:%s\n' "$RED" "$_leg" "$RST" >&2
    printf '%s%s%s\n' "$DIM" "$_diff" "$RST" >&2
    return 1
  fi
  printf '  %s· مُرشِّحاتُ %s: %d حزمةً طابقتْ المُشتَقَّ بعينِهِ%s\n' "$DIM" "$_leg" "${#_paths[@]}" "$RST"
}

printf '%s── الاختبارات — شِقّانِ (M0-35)%s\n' "$BLD" "$RST"
printf '  %sالمتوازي:%s %d حزمةً · %sالمُسلسَلُ (بوّاباتٌ على قاعدةٍ واحدةٍ):%s %d حزمةً\n' \
  "$DIM" "$RST" "${#PAR[@]}" "$DIM" "$RST" "${#GATE[@]}"

FAILED=0


if [[ "${1:-}" == "--verify-filters" ]]; then
  # نمطُ الحارسِ (M0-42): يُثبِتُ أنَّ مُرشِّحاتِ الشِّقَّينِ تُطابِقُ المُشتَقَّ
  # من القرصِ **مجموعةً بمجموعةٍ** — بلا تشغيلِ اختبارٍ واحدٍ. ووسمُ الخِتامِ
  # إلزاميٌّ كوسمِ `--print-groups`: خرجٌ بلا وسمٍ مقطوعٌ ولا يُقرأُ نجاحاً.
  _assert_filter_coverage PAR 'المتوازي' || exit 1
  _assert_filter_coverage GATE 'المُسلسَل' || exit 1
  printf 'FILTERS\tOK\t%s\n' "$(( ${#PAR[@]} + ${#GATE[@]} ))"
  exit 0
fi

if (( ${#PAR[@]} > 0 )); then
  printf '\n%s[1/2] الشِّقُّ المتوازي%s\n' "$BLD" "$RST"
  FILTERS=(); for p in "${PAR[@]}"; do FILTERS+=("--filter=./$p"); done
  _assert_filter_coverage PAR 'المتوازي' || exit 1
  pnpm -r "${FILTERS[@]}" test || FAILED=1
fi

# يجري **دائماً** ولو أخفقَ الشِّقُّ الأوّلُ: بوّابةٌ لا تُقاسُ لأنَّ وحدةً
# أخفقَت هيَ بوّابةٌ مُعطَّلةٌ بالتبعيّةِ — والحكمُ يُجمَعُ لا يُقصَّرُ.
printf '\n%s[2/2] الشِّقُّ المُسلسَلُ — --workspace-concurrency=1%s\n' "$BLD" "$RST"
FILTERS=(); for p in "${GATE[@]}"; do FILTERS+=("--filter=./$p"); done
_assert_filter_coverage GATE 'المُسلسَل' || exit 1
pnpm -r --workspace-concurrency=1 "${FILTERS[@]}" test || FAILED=1

echo
if (( FAILED == 0 )); then
  printf '%s✓ الاختبارات: الشِّقّانِ نجحا (%d متوازيةً · %d مُسلسَلةً).%s\n' \
    "$GRN" "${#PAR[@]}" "${#GATE[@]}" "$RST"
else
  printf '%s✗ الاختبارات: أخفقَ شِقٌّ — والحكمُ لا يُقصَّرُ عندَ أوّلِ إخفاقٍ.%s\n' \
    "$RED" "$RST"
fi
exit "$FAILED"
