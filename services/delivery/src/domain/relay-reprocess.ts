/**
 * إعادةُ صفٍّ مسمومٍ إلى الطابورِ — القرارُ وحدَهُ (المراجعةُ 22/N · M5-13R · ADR-026 §4.24).
 *
 * ## ما الذي يُصلِحُهُ هذا الملفُّ
 *
 * [`relay-dead-letters.ts`](./relay-dead-letters.ts) أعطى المُشغِّلَ **عيناً**:
 * يعرفُ أنَّ في الدفترِ صفوفاً مسمومةً وكم عمرُ أقدمِها. ولم يُعطِهِ **يداً**:
 * يقرأُ الفقدَ ولا يملكُ أن يُعيدَهُ. وعينٌ بلا يدٍ تُنتِجُ أسوأَ حالةٍ تشغيليّةٍ —
 * تنبيهٌ يرِنُّ على ما لا يُفعَلُ فيهِ شيءٌ، فيُصمَّتُ التنبيهُ بعدَ أسبوعَينِ.
 *
 * ## واكتشافانِ قِيسا قبلَ كتابةِ سطرٍ، وهُما سببُ شكلِ هذا المسارِ
 *
 * **(أ) الدفترُ لا يحفظُ ما يُعادُ.** `delivery_relay_consumed_events` و
 * `delivery_inventory_relay_consumed_events` فيهما `event_id` و`event_type` و
 * `aggregate_*` والحالةُ والمحاولاتُ و`last_error` — **ولا حمولةَ ولا
 * `occurred_at`**. فما يُظَنُّ «طابورَ رسائلَ ميتةٍ» هوَ **دفترُ أحكامٍ** لا دفترُ
 * رسائلَ. ولذلكَ **لا تُنسَخُ حمولةٌ هنا**: نسخُها كانَ سيُنشِئُ مصدرَ حقيقةٍ
 * مُكرَّراً ينحرِفُ عن الصندوقِ الصادرِ بلا أن يُسقِطَ اختباراً — وهوَ نفسُ
 * العيبِ الذي رفضَهُ صدرُ §4.23 نصّاً. فالحدثُ يُقرأُ **من مصدرِهِ** دائماً.
 *
 * **(ب) إرجاعُ نقطةِ التقدُّمِ وحدَهُ لا يُعيدُ شيئاً.**
 * [`relay.ts`](../relay.ts) يُقصِّرُ الدورةَ على كلِّ حدثٍ بحالةٍ **نهائيّةٍ**
 * («a terminally-consumed event is a no-op»)، و`poisoned` نهائيّةٌ — فالصفُّ
 * يُقرأُ ثانيةً ويُعادُ `poisoned` **بلا محاولةٍ واحدةٍ**. أي أنَّ `replayFrom`
 * الموجودَ **يبدو** مسارَ إعادةٍ وليسَ كذلكَ لهذهِ الصفوفِ بعينِها. ولولا القياسُ
 * لكُتِبَ نداءٌ «يُعيدُ» ويُوثَّقُ أنّهُ يُعيدُ **وهوَ لا يُعيدُ** — عطبٌ صامتٌ
 * بشهادةٍ مكتوبةٍ، وذلكَ أسوأُ من غيابِ المسارِ.
 *
 * **فالمسارُ حركتانِ لا واحدةٌ، وفي معاملةٍ واحدةٍ:** رفعُ نهائيّةِ الصفِّ
 * (`poisoned` → `pending`) **ثمَّ** إرجاعُ نقطةِ التقدُّمِ. وفصلُهما على
 * معاملتَينِ كانَ يُنتِجُ حالتَينِ كاذبتَينِ: صفٌّ رُفِعَ ولا نقطةَ أُرجِعَت فلا
 * يُقرأُ أبداً (فقدٌ **مُخفىً** لأنَّ المقياسَ لم يعُدْ يعُدُّهُ)، أو نقطةٌ
 * أُرجِعَت ولا صفَّ رُفِعَ فيُعادُ مسحُ التاريخِ كلِّهِ بلا فائدةٍ.
 *
 * ## ولمَ **لا يُمحى** `last_error` ولا يُصفَّرُ `attempt_count`؟
 *
 * لأنَّهما الدليلُ الوحيدُ على **لِمَ** سُمَّ الصفُّ، والدفترُ لا يحفظُ تاريخاً.
 * ومسحُهُما عندَ الإعادةِ كانَ سيجعلُ كلَّ محاولةِ إنقاذٍ **تمحو سببَ العطبِ**،
 * فيُعادُ الصفُّ مرّتَينِ ولا أحدَ يعرفُ ما الذي فشلَ أوّلاً. والثمنُ مقبولٌ
 * ومُعلَنٌ: المُرحِّلُ يحسِبُ `attempt = attempt_count + 1`، فصفٌّ استنفدَ
 * محاولاتِهِ يُمنَحُ **محاولةً واحدةً** ثمَّ يُسَمُّ ثانيةً بسببٍ **جديدٍ** —
 * وهذا هوَ السلوكُ المقصودُ: الإعادةُ «جرِّبْ ثانيةً» لا «انسَ ما جرى».
 *
 * ## وحدٌّ صريحٌ: الإعادةُ **لا تَعِدُ بالنجاحِ**
 *
 * صفٌّ سُمَّ لسببٍ ثابتٍ (نسخةُ حدثٍ غيرُ مدعومةٍ · حمولةٌ بلا `job_id` · انتقالٌ
 * لا يُسقَطُ على المرآةِ) سيُسَمُّ ثانيةً فوراً ما لم يُعالَجْ سببُهُ. والنداءُ
 * يقولُ **`requeued`** — أي «أُعيدَ إلى الطابورِ» — ولا يقولُ `reprocessed` ولا
 * `recovered`. والفرقُ ليسَ لفظاً: منادٍ يقرأُ «عولِجَ» يُغلِقُ الحادثةَ.
 */

/* ════════════════════════════════════════════════════════════════════════
 * 1) الحالةُ التي تُرفَعُ إليها — **غيرُ نهائيّةٍ بالضرورةِ**
 * ════════════════════════════════════════════════════════════════════════ */

/**
 * `pending` هيَ الحالةُ الوحيدةُ غيرُ النهائيّةِ في `ConsumedStatus`، وهيَ نفسُها
 * التي يكتُبُها المُرحِّلُ عندَ فشلٍ قابلٍ للإعادةِ — فالإعادةُ **تُعيدُ الصفَّ
 * إلى مسارٍ قائمٍ مُختبَرٍ** ولا تخترعُ حالةً ثانيةَ عشرةَ. وحالةٌ جديدةٌ
 * (`requeued` مثلاً) كانَت ستوجِبُ هجرةً على قيدِ `CHECK` في الدفترَينِ، وتوسيعَ
 * كلِّ `isTerminal` و`switch` في المُرحِّلَينِ، وتُنشئُ فرعاً ثانياً يفعلُ ما
 * يفعلُهُ `pending` حرفاً — وهوَ ازدواجٌ بلا مُقابِلٍ.
 */
export const RELAY_REQUEUE_TARGET_STATUS = "pending" as const;

/* ════════════════════════════════════════════════════════════════════════
 * 2) شكلُ القرارِ
 * ════════════════════════════════════════════════════════════════════════ */

/**
 * أسبابُ الرفضِ — **مُعدَّدةٌ لا نصٌّ حُرٌّ**، كي يستطيعَ منادٍ أن يفرِّقَ
 * بينَها بلا مطابقةِ سلاسلَ.
 */
export type RelayRequeueRejectionReason =
  /** لا صفَّ بهذا `event_id` في هذا الدفترِ — وهذا **ليسَ** نجاحاً صامتاً. */
  | "not_found"
  /**
   * الصفُّ موجودٌ وحالتُهُ ليست `poisoned`. ولمَ رفضٌ لا تجاهُلٌ؟ لأنَّ إعادةَ
   * صفٍّ `applied` تعني إعادةَ تطبيقِ أثرٍ وقعَ؛ والتماثُليّةُ تحميهِ فعلاً،
   * لكنَّ **السماحَ بالنداءِ** يجعلُ خطأَ مُشغِّلٍ في نسخِ مُعرِّفٍ فعلاً
   * مقبولاً بلا أثرٍ مرئيٍّ — فلا يتعلَّمُ أنَّهُ أخطأَ. والرفضُ يُعلِّمُهُ.
   */
  | "not_poisoned";

export interface RelayRequeueRejected {
  readonly outcome: "rejected";
  readonly reason: RelayRequeueRejectionReason;
  /** الحالةُ المقروءةُ فعلاً — `null` حينَ لا صفَّ. لا تُخمَّنُ ولا تُطوى. */
  readonly observedStatus: string | null;
}

export interface RelayRequeueAccepted {
  readonly outcome: "requeued";
  /** الحالةُ قبلَ الرفعِ — دائماً `poisoned`، وتُنشَرُ كي يكونَ الأثرُ مقروءاً. */
  readonly previousStatus: "poisoned";
}

export type RelayRequeueDecision = RelayRequeueAccepted | RelayRequeueRejected;

/* ════════════════════════════════════════════════════════════════════════
 * 3) القرارُ — دالّةٌ نقيّةٌ
 * ════════════════════════════════════════════════════════════════════════ */

/**
 * يُقرِّرُ هل يُعادُ الصفُّ، من حالتِهِ المقروءةِ وحدَها.
 *
 * ولمَ دالّةٌ نقيّةٌ ومنفصلةٌ عن المُحوِّلِ؟ لأنَّ الشرطَ («المسمومُ وحدَهُ
 * يُعادُ») حكمُ نطاقٍ لا تفصيلَ SQL؛ ودفنُهُ في `WHERE consumed_status =
 * 'poisoned'` كانَ سيجعلَ الرفضَ **صفراً من الصفوفِ المُعدَّلةِ** — ولا يُفرَّقُ
 * حينَها بينَ «لا صفَّ» و«صفٌّ ليسَ مسموماً»، فيقرأُ المُشغِّلُ الجوابَينِ
 * واحداً ويظنُّ مُعرِّفَهُ خطأً وهوَ صحيحٌ.
 */
export function decideRelayRequeue(
  observedStatus: string | null,
): RelayRequeueDecision {
  if (observedStatus === null) {
    return { outcome: "rejected", reason: "not_found", observedStatus: null };
  }
  if (observedStatus !== "poisoned") {
    return { outcome: "rejected", reason: "not_poisoned", observedStatus };
  }
  return { outcome: "requeued", previousStatus: "poisoned" };
}
