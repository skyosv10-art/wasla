/**
 * `Retry-After` على حدِّ التوصيلِ — قيمةٌ **مقيسةٌ** لا مُقدَّرةٌ
 * (ADR-026 §4.21 · المراجعةُ 19/N · رفعُ دَينِ §4.10-1 القائمِ منذُ المراجعةِ 7/N).
 *
 * ## لماذا ملفٌّ خالصٌ لا سطرانِ في `errors.ts`؟
 *
 * لأنَّ السؤالَ «هل يُعادُ هذا الطلبُ، وبعدَ كم؟» سؤالُ **نطاقٍ** لا سؤالُ نقلٍ:
 * جوابُهُ يأتي من حقيقةٍ عن معاملةِ قاعدةِ البياناتِ لا من تفضيلِ إطارٍ. فبقاؤهُ
 * دالّةً خالصةً يجعلُ الحقيقةَ **قابلةً للاختبارِ بلا مُشغِّلٍ ولا خادمٍ**، ويمنعُ
 * أن تُحقَنَ قيمةٌ في ترويسةٍ من موضعٍ ثانٍ لا يعلمُ بالأوّلِ.
 *
 * ## القاعدةُ: الترويسةُ ادِّعاءٌ، فلا تُقالُ إلّا حيثُ قِيسَت
 *
 * `Retry-After` ليست تلطُّفاً بالمنادي؛ هي **وعدٌ**: «أَعِدْ بعدَ هذا القدرِ فسيتغيَّرُ
 * الجوابُ». ووعدٌ لا سندَ لهُ أسوأُ من الصمتِ، لأنَّ المنادي الآليَّ يبني عليهِ
 * جدولَ إعادتِهِ. ولذلكَ الخريطةُ أدناه **مغلقةٌ ومُحصاةٌ برمزٍ واحدٍ**، وكلُّ رمزٍ
 * آخرَ — حاضرٍ أو قادمٍ — لا يحملُ الترويسةَ بالبناءِ (`undefined` ⇒ `null`) لا
 * بالسهوِ. فرمزٌ جديدٌ في الكتالوجِ يبدأُ صامتاً، ومَن أرادَهُ ناطقاً كتبَ سطرَهُ
 * هنا وكتبَ معَهُ ما قاسَ.
 *
 * ## وما الذي قِيسَ في `DELIVERY_IDEMPOTENT_REQUEST_IN_FLIGHT`؟
 *
 * أنَّ الصفَّ الرابحَ **مُثبَتٌ في القاعدةِ لحظةَ نُطقِ الرفضِ**، لا «قيدَ المعالجةِ»
 * كما يُفهَمُ من اسمِ الرمزِ. والسبيلُ إلى ذلكَ في `store-order-store.ts`:
 * الطلبُ الخاسرُ يتعطَّلُ على الفهرسِ الفريدِ لمفتاحِ التماثُلِ حتّى **يُثبِتَ**
 * الرابحُ معاملتَهُ، ثمَّ يُطلَقُ فيرى `ON CONFLICT … DO UPDATE … WHERE
 * expires_at <= now()` صفرَ صفوفٍ (الصفُّ حيٌّ) فيرمي هذا الرمزَ. أي أنَّ
 * الجوابَ الذي سيُعيدُهُ الرابحُ **صارَ قابلاً للقراءةِ قبلَ أن يُقالَ للخاسرِ لا**.
 *
 * وقياسٌ فعليٌّ على PostgreSQL حقيقيٍّ (اثنَتا عشرةَ دورةَ تسابُقٍ بـ`Promise.all`)
 * أعطى رفضاً في إحدى عشرةَ دورةً، **وفي كلِّ رفضٍ** أعادَت المحاولةُ التاليةُ
 * **فوراً وبلا انتظارٍ** `201` معَ `Idempotent-Replay: true`. فالوقتُ اللازمُ
 * حقيقةً **صفرٌ**.
 *
 * ## فلمَ `1` لا `0`؟
 *
 * `0` صحيحٌ نحوياً (RFC 9110 §10.2.3: `delay-seconds = 1*DIGIT` عددٌ صحيحٌ غيرُ
 * سالبٍ) وصحيحٌ قياساً، لكنَّهُ يُقرأُ في المنادي الآليِّ «أَعِدْ بلا مَهَلٍ» فيصيرُ
 * حلقةً ساخنةً إن أخطأَ ظنُّنا مرّةً. و`1` هوَ **أصغرُ قيمةٍ لا تُقرأُ أمراً
 * بالدَّوَرانِ** وهيَ فوقَ المقيسِ لا تحتَهُ، فالوعدُ يبقى صادقاً بفائضٍ لا بعجزٍ.
 *
 * ## ولمَ ثابتٌ لا متغيِّرُ بيئةٍ؟
 *
 * لأنَّ القيمةَ مُشتقّةٌ من **حقيقةٍ عن المعاملةِ** لا من تفضيلٍ تشغيليٍّ. ومتغيِّرُ
 * بيئةٍ يدعو مُشغِّلاً إلى ضبطِهِ `3600` يوماً ما، فتصيرُ الترويسةُ كذبةً مُعَدّةً
 * بلا مَن يُراجِعُها.
 *
 * ## ولمَ ثوانٍ لا تاريخُ HTTP؟
 *
 * لأنَّ `delay-seconds` **لا يستلزمُ اتّفاقَ ساعتَينِ**. وتاريخُ HTTP يستلزمُ أن
 * تتّفقَ ساعةُ الخدمةِ وساعةُ المنادي، فإن تباعدَتا صارَ الوعدُ ماضياً أو بعيداً
 * بلا سببٍ — وهذا عينُ ما دفعَ القرارَ في §4.15 إلى ساعةِ القاعدةِ وحدَها.
 *
 * ## وما لا تحملُهُ هذه الخريطةُ بقصدٍ (والتعليلُ مُعلَنٌ لا مطويٌّ)
 *
 *  1. **`503 DELIVERY_MARKETPLACE_UNAVAILABLE` و`DELIVERY_DISPATCH_UNAVAILABLE`**:
 *     وهما الحالُ الذي كُتِبَت لهُ الترويسةُ في المعيارِ أصلاً — ومعَ ذلكَ لا
 *     تُقالُ، لأنّا **لا نعلمُ** متى تعودُ تبعيّةُ غيرِنا. وأيُّ رقمٍ هنا تخمينٌ
 *     يلبَسُ ثوبَ قياسٍ. ومَن أرادَها فسبيلُهُ رصدُ زمنِ العودةِ فعلاً ثمَّ نطقُ
 *     المقيسِ.
 *  2. **`409 DELIVERY_IDEMPOTENCY_KEY_REUSED`**: مفتاحٌ بجسمٍ مختلفٍ. والإعادةُ
 *     بالطلبِ نفسِهِ **لن تنجحَ أبداً** — لا بعدَ ثانيةٍ ولا بعدَ سنةٍ — فالترويسةُ
 *     هنا تدفعُ إلى إعادةٍ عقيمةٍ.
 *  3. **`409 DELIVERY_CONCURRENT_UPDATE`**: وهذا أقربُ المُبعَدَينِ، والصفُّ
 *     المُزاحِمُ مُثبَتٌ فعلاً كنظيرِهِ. لكنَّ الإعادةَ فيهِ **ليست إعادةَ الطلبِ
 *     نفسِهِ**: المنادي يحملُ نسخةً متقادمةً، فإعادةُ الطلبِ بها تُرفَضُ أبداً؛
 *     والصوابُ **قراءةٌ ثمَّ قرارٌ جديدٌ**. وترويسةٌ تقولُ «أَعِدْ بعدَ ثانيةٍ» تُغري
 *     بالإعادةِ لا بالقراءةِ، ويبقى الإرشادُ في `contracts/errors.md` نصّاً.
 *  4. **`500 DELIVERY_INTERNAL_ERROR`**: رأسُ `errors.ts` يُعلِنُ أنَّ الملاذَ
 *     الأخيرَ يقولُ «لا تُعِدْ» بقصدٍ. وترويسةٌ تنقضُ ذلكَ.
 *  5. **`429`**: لا حدَّ معدّلٍ في هذه الخدمةِ بعدُ، فلا رمزَ لهُ في الكتالوجِ.
 *     ويومَ يُوجَدُ فهذا موضعُ سطرِهِ.
 *
 * ## ولمَ ترويسةٌ ولا حقلٌ في الجسمِ؟
 *
 * لأنَّ `ErrorResponse` في `contracts/api.openapi.yml` شكلٌ منشورٌ بثلاثةِ حقولٍ،
 * وحقلٌ رابعٌ تغييرُ عقدٍ يمسُّ كلَّ منادٍ. والترويسةُ سطحُ النقلِ الذي وُضِعَ
 * لهذا المعنى في المعيارِ، ومَن لا يعرفُها يتجاهلُها بلا ضررٍ.
 */

import type { DeliveryErrorCode } from "@wasla/contracts-delivery";

import { isDeliveryError } from "../domain/errors.js";

/**
 * المَهَلُ المُعلَنُ على رفضِ التماثُلِ المتزامنِ — ثوانٍ.
 *
 * القيمةُ `1` لأنَّ المقيسَ صفرٌ (الرابحُ مُثبَتٌ لحظةَ الرفضِ) و`0` يُقرأُ أمراً
 * بالدَّوَرانِ. انظر رأسَ الملفِّ.
 */
export const DELIVERY_IN_FLIGHT_RETRY_AFTER_SECONDS = 1;

/**
 * الخريطةُ المغلقةُ: رمزُ خطأٍ ⇒ ثوانٍ. مفاتيحُها مقيَّدةٌ بـ`DeliveryErrorCode`،
 * فرمزٌ مُصحَّفٌ يُسقِطُ الأنواعَ لا يمرُّ صامتاً؛ وما ليسَ فيها لا ترويسةَ لهُ.
 */
const RETRY_AFTER_SECONDS: Partial<Record<DeliveryErrorCode, number>> = {
  DELIVERY_IDEMPOTENT_REQUEST_IN_FLIGHT: DELIVERY_IN_FLIGHT_RETRY_AFTER_SECONDS,
};

/**
 * قيمةُ `Retry-After` لهذا الخطأِ، أو `null` إن لم يكن لنا ما نَعِدُ بهِ.
 *
 * تقبلُ `unknown` لأنَّ مُترجِمَ الأخطاءِ يستدعيها على ما يُرمى فعلاً — خطأُ نطاقٍ
 * أو خطأُ إطارٍ أو عيبٌ — فلا يُنقَلُ عبءُ التمييزِ إلى مواضعِ النداءِ.
 */
export function retryAfterSecondsForDeliveryError(error: unknown): number | null {
  if (!isDeliveryError(error)) return null;
  return RETRY_AFTER_SECONDS[error.code] ?? null;
}

/**
 * القيمُ المُعلَنةُ كلُّها — للاختبارِ وحدَهُ: يُثبِتُ أنَّ كلَّ قيمةٍ عددٌ صحيحٌ
 * موجبٌ، فلا تُكتَبُ `1.5` ولا `-1` ولا `0` فتخرجَ ترويسةٌ يرفضُها المعيارُ أو
 * تدفعُ إلى حلقةٍ ساخنةٍ.
 */
export function declaredRetryAfterSeconds(): readonly number[] {
  return Object.values(RETRY_AFTER_SECONDS).filter((v): v is number => typeof v === "number");
}
