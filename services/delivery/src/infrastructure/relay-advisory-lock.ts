/**
 * قفلُ مستهلكِ المُرحِّلِ على PostgreSQL — advisory lock (M5-13R · §4.24-ب).
 *
 * ## مصدرٌ واحدٌ للمفتاحِ — والطرفانِ يستورِدانِهِ من هنا
 *
 * المستهلكُ (دفعةُ الترحيلِ) يمتلكُ القفلَ **على امتدادِ الدفعةِ كلِّها** — من قراءةِ
 * نقطةِ التقدُّمِ حتى آخرِ كتابةٍ فوقَها — بقفلٍ على مستوى **الجلسةِ**
 * (`pg_advisory_lock`): الدفعةُ ليست معاملةً واحدةً (كلُّ صفٍّ يُكتَبُ وحدهُ)،
 * فالقفلُ التشغيليُّ (`pg_advisory_xact_lock`) الذي ينفكُّ عندَ أوّلِ COMMIT كانَ
 * سيُخلِّي الميدانَ في منتصفِ الدفعةِ — وهوَ بالضبطِ اللحظةُ التي يقعُ فيها السباقُ.
 *
 * والإعادةُ (`relay-requeue-store.ts`) تمتلكُ **القفلَ التشغيليَّ نفسَهُ** داخلَ
 * معاملتِها (`pg_advisory_xact_lock`) فيُنفَكُّ آليّاً عندَ `COMMIT`/`ROLLBACK` —
 * لا `finally` تُنسى ولا سطرُ إطلاقٍ يُكتَبُ في موضعٍ بعيدٍ. والقفلانِ **مفتاحٌ
 * واحدٌ** لأنَّ الثابتَ مُصدَّرٌ من هذا الملفِّ وحدَهِ ويستورِدُهُ الطرفانِ: نسخٌ
 * ثانيةٌ للمفتاحِ كانتْ ستصيرَ مصدرَ حقيقةٍ مُكرَّراً ينجحُ في اختبارٍ وينفصلُ في
 * الإنتاجِ (سابقةُ M0-15: المرشِّحُ المكتوبُ مرّتَينِ انحرفَ سنةً كاملةً بلا كاشفٍ).
 *
 * ## المفتاحُ: `(NAMESPACE, hashtext(consumerId))`
 *
 * PostgreSQL يقبلُ مفتاحًا واحدًا كبيرًا أو زوجًا من `int` — والزوجُ يُعطينا
 * **نطاقَ أسماءَ**: النطاقُ ثابتٌ لكلِّ أقفالِ المُرحِّلاتِ في هذه الخدمةِ، والجزءُ
 * الثاني مشتقٌّ من اسمِ المُستهلِكِ. فدفترانِ ⇒ مفتاحانِ مختلفانِ (توزيعٌ ·
 * مخزونُ السوقِ)، ولا يحجبُ أحدُهُما الآخرَ. و`hashtext` دالةٌ داخليةٌ ثابتةُ
 * الناتجِ داخلَ الإصدارِ الواحدِ — والكافّتانِ (`$1, $2`) مُعامِلاتٌ مُمرَّرةٌ لا
 * تركيبُ نصٍّ، فلا مُدخَلَ يصلُ الاستعلامَ.
 *
 * ## انسدادٌ محدودٌ لا انسدادٌ أبديٌّ
 *
 * الطرفُ الثاني ينتظرُ حتى يُفرِجَ الأولُ — ومدةُ الانتظارِ **محدودةٌ بالبناءِ**:
 * الدفعةُ تمتلكُ القفلَ لامدىً محسومًا (قراءةُ حدِّ `batchSize` من الصفوفِ ثمَّ
 * كتابتُها)، فإعادةٌ تصلُ في منتصفِ دفعةٍ تنتظرُ انتهاءَها لا تتزاحمُ معَها.
 * والترتيبُ داخلَ الانتظارِ عادلٌ (طابورُ PostgreSQL للاستشاريّاتِ FIFO) — فلا
 * تجويعَ.
 *
 * ## لماذا لا يُستعمَلُ هذا القفلُ لغيرِ المُرحِّلَينِ
 *
 * النطاقُ مُخصَّصٌ لأقفالِ مستهلكِ المُرحِّلاتِ؛ استعمالُهُ في غرضٍ آخرَ (قفلُ
 * طلبٍ · قفلُ جردٍ) كانَ سيخلطَ مساراتِ انتظارٍ لا علاقةَ بينَها ويفتحُ بابًا
 * لانسدادٍ متبادلٍ لا يُرى إلا تحتَ حِملٍ. ولكلِّ غرضٍ نطاقُهُ.
 */

import type { Pool, PoolClient } from "pg";
import type { RelayConsumerLock } from "../ports.js";

/**
 * نطاقُ أسماءِ أقفالِ المُرحِّلاتِ — الثابتُ الوحيدُ الذي يُشتقُّ منهِ المفتاحُ
 * على وجهَينِ (جلسةٍ للمستهلكِ · تشغيليٍّ للإعادةِ). الرقمُ اعتباطيٌّ مقصودٌ
 * بعيدٍ عنْ نطاقاتِ أقفالٍ أخرى في المنظومةِ.
 */
export const RELAY_ADVISORY_LOCK_NAMESPACE = 42626;

/**
 * حيازةُ قفلِ الجلسةِ على مُستهلِكٍ — **الجملةُ الأصلُ** التي يستعملُها الطرفانِ
 * لا نسخةً من نصِّها: مُحوِّلُ الإعادةِ يبني جملتَهُ (التشغيليّةَ) فوقَ الثابتِ
 * نفسِهِ فلا انحرافَ بينَ المفتاحَينِ.
 */
export function relayAdvisoryLockKey(consumerId: string): readonly [number, string] {
  return [RELAY_ADVISORY_LOCK_NAMESPACE, consumerId];
}

/**
 * القفلُ الاستشاريُّ على مستوى الجلسةِ — ينفذُ `fn` داخلَ الحيازةِ ويُطلِقُها
 * **دائمًا**. والاتّصالُ **مُستأجَرٌ من المجمَّعِ** (لا يُخلَقُ لكلِّ دفعةٍ): فالحيازةُ
 * تتطلّبُ جلسةً واحدةً ثابتةً — `pg_advisory_lock` على اتّصالٍ ثمَّ `pg_advisory_unlock`
 * على اتّصالٍ آخرَ يعيدُ خطأً لأنَّ الأقفالَ الاستشاريّةَ **مِلكُ الجلسةِ** لا
 * المُعامِلةِ.
 */
export class PostgresRelayConsumerLock implements RelayConsumerLock {
  constructor(private readonly pool: Pool) {}

  async withConsumerLock<T>(consumerId: string, fn: () => Promise<T>): Promise<T> {
    const [ns, key] = relayAdvisoryLockKey(consumerId);
    const client: PoolClient = await this.pool.connect();
    try {
      // الحيازةُ على الجلسةِ المُستأجَرةِ نفسِها — والقفلُ ينتمي إليها حصراً.
      await client.query("SELECT pg_advisory_lock($1, hashtext($2))", [ns, key]);
      try {
        return await fn();
      } finally {
        // يُنفَّذُ نجحَ `fn` أم رَمى — والإطلاقُ على الجلسةِ نفسِها لا غيرَ.
        await client.query("SELECT pg_advisory_unlock($1, hashtext($2))", [ns, key]);
      }
    } finally {
      client.release();
    }
  }
}
