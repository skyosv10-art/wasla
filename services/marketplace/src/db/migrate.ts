/**
 * الترحيلُ: تطبيقُ `contracts/schema.sql` **حرفاً** لا توليدُ DDL من مرآةِ TypeScript.
 *
 * ## القرار: العقدُ هو الترحيل
 *
 * `schema.sql` مُغلَّفٌ في `BEGIN;`/`COMMIT;` من المراجعة 1/6، وكلُّ جدولٍ فيه
 * `CREATE TABLE IF NOT EXISTS` وكلُّ فهرسٍ `CREATE INDEX IF NOT EXISTS` — فتشغيلُه مرّتَين
 * سالمٌ، وتشغيلُه جزئيّاً مستحيل: إمّا تُطبَّق العشرةُ كلُّها أو لا شيء.
 *
 * والأرخصُ الخاطئُ هو `drizzle-kit generate`: يُنتج DDL من `schema.ts` فيصير المخطّطُ في
 * القاعدةِ صورةَ **المرآةِ** لا صورةَ العقد. وأوّلُ فحصٍ بلا اسمٍ لا يعرف Drizzle كيف يُعبّر
 * عنه (وهي هنا العشراتُ: صيغُ المُعرّفاتِ وحدودُ الأطوالِ وتعداداتُ الحالات) يسقط صامتاً،
 * فتقبل القاعدةُ `state = 'aproved'` ويظنّ الجميعُ أنّ القيدَ موجودٌ لأنّه مكتوبٌ في العقد.
 *
 * ## ولا Drizzle في التنفيذِ هنا بقصد
 *
 * `pool.query(ddl)` لا `db.execute(sql.raw(ddl))`: Drizzle يُحلّل النصَّ ويُعيد صياغتَه في
 * مسارِه، ونصُّ العقدِ فيه `$$`-quoting وتعليقاتٌ عربيّةٌ وسطورٌ فارغةٌ لا معنى لتحليلها. ومسارُ
 * `pg` المباشرُ يُنفّذ النصَّ كما هو ويُعيد خطأَ Postgres بحرفِه ورقمِ سطرِه — وهذا فرقٌ يُقاس
 * في الدقائقِ عند أوّلِ خطأٍ في الـDDL.
 *
 * ## ولا بذرَ بياناتٍ هنا
 *
 * `store_categories` تبقى فارغةً بعد الترحيل. وبذرُ التصنيفاتِ الأوّليّةِ في الترحيلِ كان
 * سيجعل كلَّ اختبارِ تكاملٍ يبدأ ببياناتٍ لم يطلبها، فيمرّ اختبارُ «منتجٌ في تصنيفٍ ورقةٍ»
 * لأنّ الورقةَ كانت مبذورةً لا لأنّ الكودَ أنشأها. والبذرُ مهمّةُ المراجعة 5/6 (خطوةٌ مُسمّاةٌ
 * في الخارطة) لأنّه بيانُ تشغيلٍ لا بنيةَ مخطّط.
 *
 * ## ولا قراءةَ بيئةٍ ولا ساعةَ نظامٍ
 *
 * `connectionString` وسيطٌ، ومسارُ العقدِ يُشتقّ من موقعِ هذا الملفِّ لا من `cwd`: مُنادٍ يركض
 * من جذرِ المستودعِ ومُنادٍ يركض من مجلَّدِ الخدمةِ يجب أن يقرآ نفسَ الملفّ. وقارئُ البيئةِ
 * الوحيدُ هو `migrate-cli.ts` — مُعلَناً بالاسمِ في `__tests__/purity.test.ts`.
 */

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import type { Pool } from "pg";

/** جذرُ الخدمةِ: `src/db/` ← `src/` ← جذرُ الحزمة. */
const SERVICE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

/** مسارُ العقدِ الوحيدُ المُعتمَد — يُقرأ في الاختبارِ نفسِه كي لا يوجد مساران. */
export const SCHEMA_CONTRACT_PATH = join(SERVICE_ROOT, "contracts", "schema.sql");

export function readSchemaContract(): string {
  return readFileSync(SCHEMA_CONTRACT_PATH, "utf8");
}

/**
 * يُطبّق نصَّ العقدِ على القاعدةِ المُشار إليها بالمسبح.
 *
 * لا `BEGIN` هنا: النصُّ يحمل معاملتَه بنفسِه. وإحاطتُه بمعاملةٍ ثانيةٍ كانت ستُنتج معاملةً
 * متداخلةً يُحذّر منها Postgres ويتجاهلها، فيبدو السجلُّ كأنّ شيئاً غريباً يحدث في كلِّ ترحيل.
 */
export async function applyMarketplaceSchema(pool: Pool): Promise<void> {
  await pool.query(readSchemaContract());
}
