/**
 * تصفيحٌ بمفتاحٍ مُركَّب: نوعُ الصفحةِ وحدُّها في موضعٍ واحد.
 *
 * ## لماذا ملفٌّ مستقلٌّ لا نسختان
 *
 * ثلاثةُ مخازنَ تُصفِّح (المتاجرُ · المنتجاتُ · السجلّ)، وحدُّ الصفحةِ رقمٌ في العقد. ونسخُ
 * الحدِّ في كلٍّ منها كان سيجعل مساراً واحداً يُعيد مئتَي صفٍّ وآخرَ يُعيد خمسينَ بعد أوّلِ
 * تعديلٍ يُنسى في موضع. والحدُّ يُقصُّ هنا حتى لو نسي الحدُّ فحصَه: مُنادٍ داخليٌّ لا يمرّ من
 * HTTP يبقى غيرَ قادرٍ على طلبِ الجدولِ كلِّه في استعلام.
 *
 * ## لماذا لا `OFFSET`
 *
 * `OFFSET n` يقرأ الصفوفَ التي تجاوزها ثمّ يُهملها، فتكلفةُ الصفحةِ العاشرةِ عشرةُ أمثالِ
 * الأولى — **ثمّ يُخطئ**: صفٌّ يُدرَج بين طلبَين يُزحزح كلَّ شيءٍ فيُقرأ صفٌّ مرّتَين أو
 * يُقفَز صفٌّ بلا قراءة. والمفتاحُ المُركَّبُ يُصيب فهرساً مُعلَناً ويبقى صادقاً مع الكتابةِ
 * المتزامنة.
 *
 * ## لماذا `limit + 1`
 *
 * لمعرفةِ «هل بعد هذه الصفحةِ شيء؟» بلا `count(*)` على المجموعةِ كلِّها. والزائدُ يُسقَط ولا
 * يُعاد. وغيابُ موضعِ الاستمرارِ هو إشارةُ الانتهاءِ **الوحيدة**: عددُ الصفوفِ ليس إشارةً،
 * لأنّ صفحةً تامّةً قد تكون الأخيرة، وصفحةً ناقصةً قد يكون بعدَها المزيدُ عندما يُرشِّح
 * المجالُ صفوفاً بعد القراءة.
 */

import { validationFailed } from "../domain/errors.js";

/** حدُّ الصفحةِ كما يُعلِنه `api.openapi.yml` — يُفحَص على الحدِّ ويُقصُّ هنا ثانيةً. */
export const PAGE_LIMIT_DEFAULT = 50;
export const PAGE_LIMIT_MAX = 200;

/** صفحةٌ: صفوفٌ ثمّ موضعُ استمرارٍ إن بقي بعدها شيء. */
export interface Page<TItem, TCursor> {
  readonly items: ReadonlyArray<TItem>;
  readonly nextCursor?: TCursor;
}

/** يُصحِّح الحدَّ أو يرفضه — لا قصَّ صامتاً لقيمةٍ غيرِ صحيحةٍ إلى الافتراضيّ. */
export function boundedPageLimit(limit?: number): number {
  const requested = limit ?? PAGE_LIMIT_DEFAULT;
  if (!Number.isSafeInteger(requested) || requested < 1) {
    throw validationFailed("limit", `1..${PAGE_LIMIT_MAX}`);
  }
  return Math.min(requested, PAGE_LIMIT_MAX);
}
