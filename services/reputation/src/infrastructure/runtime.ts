/**
 * محوّلاتُ العمليّة الحقيقية: ساعةٌ ومُعرّفات (Phase 09 · المراجعة 4/6).
 *
 * ## لماذا ملفٌّ مستقلّ عن `in-memory.ts`
 *
 * `in-memory.ts` بيئةُ اختبار: ساعتُها تُحرَّك بيد ومُعرّفاتُها متسلسلة كي يُسمّي الفشلُ
 * `…-000000000007` بدل قيمةٍ تختلف في كل تشغيل. وما هنا نقيضُ ذلك تماماً — ساعةُ النظام
 * ومُعرّفاتُ التعمية — فوضعُهما معاً كان سيجعل استيراداً واحداً خاطئاً في اختبارٍ يجلب
 * زمناً حقيقياً إلى مجموعةٍ بُنيت كلُّها على أنّ الزمنَ مُدخَل. وفي هذه الخدمة بالذات
 * الخطرُ أكبر: التلاشي ونوافذُ الاحتيال دوالٌّ في الزمن، فاختبارٌ يقرأ «الآن» يفشل عند
 * منتصف الليل ثمّ ينجح صباحاً.
 *
 * ولا شيءَ في هذا الملف يقرأ متغيّرَ بيئة: اختيارُ المحوّلات كلُّه في `http/server.ts`.
 */

import { randomUUID } from "node:crypto";

import type { Clock, IdGenerator } from "../ports.js";

/** ساعةُ النظام — المحوّلُ الوحيد الذي يقرأ الزمنَ الحقيقي. */
export class SystemClock implements Clock {
  now(): string {
    return new Date().toISOString();
  }
}

/** مُعرّفاتُ UUID v4 حقيقية. */
export class CryptoIdGenerator implements IdGenerator {
  uuid(): string {
    return randomUUID();
  }
}
