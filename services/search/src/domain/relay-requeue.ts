/**
 * إعادةُ صفٍّ مسمومٍ في دفترِ البحثِ إلى الطابورِ — القرارُ وحدَهُ
 * (فجوةُ `G5` · موجةُ **اليدِ** · ADR-026 §4.24 · `CLM-0248`).
 *
 * ## ما الذي يُصلِحُهُ هذا الملفُّ
 *
 * موجةُ العينِ ([`relay-dead-letters.ts`](./relay-dead-letters.ts)) أعطَت
 * المُشغِّلَ أن **يعرِفَ**: كم صفّاً مسموماً في `search_relay_consumed_events`
 * وكم عمرُ أقدمِها. ولم تُعطِهِ أن **يفعلَ**. وعينٌ بلا يدٍ أسوأُ حالةٍ
 * تشغيليّةٍ: تنبيهٌ يرِنُّ على ما لا سبيلَ إلى معالجتِهِ، فيُصمَّتُ بعدَ
 * أسبوعَينِ — وبعدَ التصميتِ لا يُرى المسمومُ **الجديدُ** أيضاً.
 *
 * ## واكتشافانِ قِيسا في شفرةِ البحثِ نفسِها قبلَ كتابةِ سطرٍ
 *
 * **(أ) `poisoned` نهائيّةٌ، فـ`replayFrom` وحدَهُ لا يُعيدُ هذهِ الصفوفَ.**
 * [`relay.ts`](../relay.ts) الخطوةُ 1: `isTerminal(status)` هيَ
 * `status !== "pending"`، وصفٌّ نهائيٌّ **يُقصَّرُ فوراً** («duplicate delivery
 * — already terminal») بلا محاولةٍ واحدةٍ. فإرجاعُ نقطةِ التقدُّمِ وحدَهُ
 * يُعيدُ قراءةَ الصفِّ ويُعيدُ الجوابَ `poisoned` كما هوَ. أي أنَّ `replayFrom`
 * الموجودَ **يبدو** مسارَ إعادةٍ ولا يكونُ كذلكَ لهذهِ الصفوفِ بعينِها — ولولا
 * قياسُهُ لكُتِبَ نداءٌ «يُعيدُ» ووُثِّقَ أنّهُ يُعيدُ **وهوَ لا يُعيدُ**، وهذا
 * عطبٌ صامتٌ بشهادةٍ مكتوبةٍ، وهوَ أسوأُ من غيابِ المسارِ.
 *
 * **(ب) والرفعُ وحدَهُ لا يُعيدُ شيئاً أيضاً.** نقطةُ التقدُّمِ تجاوزَت الصفَّ
 * حينَ سُمَّ (`relay.ts`: كلُّ ما ليسَ `pending` يُقدِّمُ النقطةَ عمداً كي لا
 * يحجُزَ حدثٌ فاسدٌ التيّارَ)، فصفٌّ رُفِعَ إلى `pending` ولا نقطةَ أُرجِعَت
 * **لا يُقرأُ أبداً** — ويسقُطُ في الوقتِ نفسِهِ من مقياسِ موجةِ العينِ لأنَّهُ
 * لم يعُدْ `poisoned`. أي أنَّ نصفَ الفعلِ يجعلُ الفقدَ **أخفى ممّا كانَ**،
 * وذلكَ أسوأُ من عدمِ الإعادةِ أصلاً.
 *
 * **فالفعلُ حركتانِ لا واحدةٌ، وفي معاملةٍ واحدةٍ:** رفعُ نهائيّةِ الصفِّ
 * (`poisoned` → `pending`) **ثمَّ** إرجاعُ نقطةِ التقدُّمِ.
 *
 * ## ولمَ **لا يُمحى** `last_error` ولا يُصفَّرُ `attempt_count`؟
 *
 * لأنَّهما الدليلُ الوحيدُ على **لِمَ** سُمَّ الصفُّ؛ والدفترُ لا يحفظُ تاريخاً
 * (لا `updated_at` فيهِ أصلاً — وهوَ الحدُّ المنشورُ في موجةِ العينِ). ومحوُهُما
 * عندَ الإعادةِ كانَ سيجعلُ كلَّ محاولةِ إنقاذٍ **تمحو سببَ العطبِ**، فيُعادُ
 * الصفُّ مرّتَينِ ولا أحدَ يعرِفُ ما الذي فشلَ أوّلاً.
 *
 * والثمنُ مقبولٌ **ومُعلَنٌ**: المُرحِّلُ يحسِبُ `attempt = attempt_count + 1`
 * ويُسَمِّمُ عندَ `attempt > maxAttempts` (الافتراضُ 5). فصفٌّ استنفدَ محاولاتِهِ
 * يُسَمُّ ثانيةً **في أوّلِ دورةٍ** بسببٍ جديدٍ يُكتَبُ فوقَ القديمِ. وهذا هوَ
 * السلوكُ المقصودُ: الإعادةُ «جرِّبْ ثانيةً» لا «ابدأْ من جديدٍ»، ولا تُعِدُ
 * بمحاولاتٍ لم يأذَنْ بها ضبطُ المُرحِّلِ.
 *
 * ## وحدٌّ صريحٌ: الإعادةُ **لا تَعِدُ بالنجاحِ**
 *
 * صفٌّ سُمَّ لسببٍ ثابتٍ (`unsupported event_version` · `catalog product not
 * found`) سيُسَمُّ ثانيةً ما لم يُعالَجْ سببُهُ خارجَ هذا المسارِ. والجوابُ
 * يقولُ **`requeued`** — «أُعيدَ إلى الطابورِ» — ولا يقولُ `reprocessed` ولا
 * `recovered`. والفرقُ ليسَ لفظاً: منادٍ يقرأُ «عولِجَ» يُغلِقُ الحادثةَ.
 */

/* ════════════════════════════════════════════════════════════════════════
 * 1) الحالةُ التي يُرفَعُ إليها — **غيرُ نهائيّةٍ، وقائمةٌ مُختبَرةٌ**
 * ════════════════════════════════════════════════════════════════════════ */

/**
 * `pending` هيَ الحالةُ الوحيدةُ غيرُ النهائيّةِ في `ConsumedStatus`
 * (`isTerminal` هيَ `status !== "pending"` حرفاً)، وهيَ نفسُها التي يكتُبُها
 * المُرحِّلُ عندَ فشلٍ قابلٍ للإعادةِ. فالإعادةُ **تُعيدُ الصفَّ إلى مسارٍ قائمٍ
 * مُختبَرٍ** ولا تخترعُ حالةً سابعةً.
 *
 * وحالةٌ جديدةٌ (`requeued` مثلاً) كانت ستوجِبُ هجرةً على قيدِ `CHECK` في
 * `search_relay_consumed_events`، وتوسيعَ `isTerminal` وكلِّ فرعِ حالةٍ في
 * المُرحِّلِ، وتُنشئُ فرعاً ثانياً يفعلُ ما يفعلُهُ `pending` حرفاً — ازدواجٌ بلا
 * مُقابِلٍ، وسطحُ انحرافٍ جديدٌ في قيدٍ قاعديٍّ.
 */
export const SEARCH_REQUEUE_TARGET_STATUS = "pending" as const;

/* ════════════════════════════════════════════════════════════════════════
 * 2) شكلُ القرارِ
 * ════════════════════════════════════════════════════════════════════════ */

/**
 * أسبابُ الرفضِ — **مُعدَّدةٌ لا نصٌّ حُرٌّ**، كي يفرِّقَ بينَها منادٍ بلا
 * مطابقةِ سلاسلَ.
 */
export type SearchRequeueRejectionReason =
  /** لا صفَّ بهذا `outbox_id` في هذا الدفترِ — وهذا **ليسَ** نجاحاً صامتاً. */
  | "not_found"
  /**
   * الصفُّ موجودٌ وحالتُهُ ليست `poisoned`. ولمَ رفضٌ لا تجاهُلٌ؟ لأنَّ إعادةَ
   * صفٍّ `applied` تعني إعادةَ تطبيقِ أثرٍ وقعَ؛ والتماثُليّةُ تحميهِ فعلاً،
   * لكنَّ **السماحَ بالنداءِ** يجعلُ خطأَ مُشغِّلٍ في نسخِ مُعرِّفٍ فعلاً
   * مقبولاً بلا أثرٍ مرئيٍّ — فلا يتعلَّمُ أنَّهُ أخطأَ. والرفضُ يُعلِّمُهُ.
   */
  | "not_poisoned";

export interface SearchRequeueRejected {
  readonly outcome: "rejected";
  readonly reason: SearchRequeueRejectionReason;
  /** الحالةُ المقروءةُ فعلاً — `null` حينَ لا صفَّ. لا تُخمَّنُ ولا تُطوى. */
  readonly observedStatus: string | null;
}

export interface SearchRequeueAccepted {
  readonly outcome: "requeued";
  /** الحالةُ قبلَ الرفعِ — دائماً `poisoned`، وتُنشَرُ كي يكونَ الأثرُ مقروءاً. */
  readonly previousStatus: "poisoned";
}

export type SearchRequeueDecision = SearchRequeueAccepted | SearchRequeueRejected;

/* ════════════════════════════════════════════════════════════════════════
 * 3) القرارُ — دالّةٌ نقيّةٌ
 * ════════════════════════════════════════════════════════════════════════ */

/**
 * يُقرِّرُ هل يُعادُ الصفُّ، من حالتِهِ المقروءةِ وحدَها.
 *
 * ولمَ دالّةٌ نقيّةٌ منفصلةٌ عن المُحوِّلِ؟ لأنَّ الشرطَ («المسمومُ وحدَهُ
 * يُعادُ») حكمُ نطاقٍ لا تفصيلَ SQL؛ ودفنُهُ في `WHERE status = 'poisoned'` كانَ
 * سيجعلُ الرفضَ **صفراً من الصفوفِ المُعدَّلةِ**، ولا يُفرَّقُ حينَها بينَ «لا
 * صفَّ» و«صفٌّ ليسَ مسموماً» — فيقرأُ المُشغِّلُ الجوابَينِ واحداً ويظنُّ
 * مُعرِّفَهُ خطأً وهوَ صحيحٌ.
 */
export function decideSearchRequeue(
  observedStatus: string | null,
): SearchRequeueDecision {
  if (observedStatus === null) {
    return { outcome: "rejected", reason: "not_found", observedStatus: null };
  }
  if (observedStatus !== "poisoned") {
    return { outcome: "rejected", reason: "not_poisoned", observedStatus };
  }
  return { outcome: "requeued", previousStatus: "poisoned" };
}
