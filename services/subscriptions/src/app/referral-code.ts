/**
 * صياغةُ رمزِ الإحالة — **دالّةٌ من المُعرّف** لا قيمةٌ عشوائيّة.
 *
 * ## لماذا مُشتَقٌّ ولم يكن عشوائيّاً
 *
 * العشوائيةُ كانت ستُلزمنا حلقةَ «اقترح ثمّ افحص التعارض ثمّ أعد»، وهي حلقةٌ تُنادي القاعدةَ
 * عدداً غيرَ محدودٍ من المرّات وتُدخل `Math.random` إلى خدمةٍ يمنعه حارسُها. والأهمُّ: رمزٌ
 * عشوائيٌّ لا يُعاد حسابُه، فلو ضاع الصفُّ لا سبيلَ لاستخراج رمزِ سائقٍ من مُعرّفه — بينما
 * الاشتقاقُ يجعل الرمزَ قابلاً لإعادةِ الحساب في أيّ وقتٍ ومن أيّ نسخةٍ من الخدمة.
 *
 * والاشتقاقُ **ليس** إخفاءً: من يعرف الخوارزميةَ يستطيع حسابَ رمزِ أيّ مُعرّفٍ عامّ. وهذا
 * مقبولٌ لأنّ الرمزَ ليس سرّاً ولا يمنح شيئاً بذاته: المطالبةُ به تُقيَّد بـ`ux_referrals_referee`
 * وبـ`ck_referrals_not_self` وبنافذةِ الخطّة، وسائقٌ حسب رمزَ غيرِه لا يجني منه إلّا أن
 * يُنسب هو نفسُه إلى ذلك الغير.
 *
 * ## ولمَ `sha256` لا مجموعُ حروفٍ بسيط
 *
 * لأنّ المُعرّفاتَ متجاورةٌ بطبعها (`WS-1000000001` ثمّ `WS-1000000002`)، ومجموعٌ بسيطٌ يُنتج
 * رموزاً متجاورةً يُخمّنها القارئُ بالعين — فيصير «رمزُ زميلي هو رمزي زائد واحد». والتلبيدُ
 * يقطع هذا التجاور بلا عشوائيّة، ونفسُ المُدخل يُعطي نفسَ المُخرج أبداً.
 *
 * وأبجديّةُ العرض 32 حرفاً داخل `[0-9A-Z]` الذي يفرضه `REFERRAL_CODE_PATTERN`: حُذفت
 * `I` و`L` و`O` و`U` (أبجديّةُ Crockford). والسببَان معاً: الرمزُ يُقرأ بالصوت ويُكتب
 * باليد فتلتبس `I`/`1` و`O`/`0` و`U`/`V`؛ والعددُ 32 قوّةُ اثنين فيقسم البايت من 256 على 32
 * قسمةً تامّةً بلا انحياز — وأبجديّةُ 34 حرفاً (حذفُ `I` و`O` وحدَهما) كانت ستجعل
 * الحرفين الأوّلين أرجحَ من بقيّةِ الأبجديّة بلا حاجة.
 */

import { createHash } from "node:crypto";

import { REFERRAL_CODE_PATTERN } from "@wasla/contracts-subscription";

import { validationFailed } from "../domain/errors.js";

/** 32 حرفاً بالعدّ — واختبارٌ يقرأ الطول فلا يمرّ حرفٌ يُحذف سهواً فيُدخل الانحياز. */
export const REFERRAL_CODE_ALPHABET = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";

/** طولُ الجسم — مطابقٌ لصيغةِ العقد `^WR-[0-9A-Z]{8}$`. */
const BODY_LENGTH = 8;

/**
 * رمزُ إحالةِ مالكٍ — نفسُه لنفس المُعرّف في كلّ نسخةٍ وكلّ وقت.
 *
 * والفحصُ الأخيرُ على صيغةِ العقد ليس زينة: أبجديّةٌ تُعدَّل غداً بحرفٍ صغيرٍ تُنتج رمزاً
 * ترفضه القاعدةُ (`ck_referral_codes_format`) في الإنتاج لا في البناء، فيُكتشف العطبُ عند
 * أوّلِ سائقٍ يطلب رمزَه. وهنا يسقط الاختبارُ في نفس اللحظة.
 */
export function referralCodeFor(ownerPublicId: string): string {
  const digest = createHash("sha256").update(ownerPublicId, "utf8").digest();
  let body = "";
  for (let index = 0; index < BODY_LENGTH; index += 1) {
    body += REFERRAL_CODE_ALPHABET[digest[index]! % REFERRAL_CODE_ALPHABET.length];
  }
  const code = `WR-${body}`;
  if (!REFERRAL_CODE_PATTERN.test(code)) {
    throw validationFailed("referral_code", "code matching the contract pattern");
  }
  return code;
}
