/**
 * الحدُّ الوحيدُ الذي يقرأ ساعةَ النظام — **ملفٌّ واحدٌ مُعلَنٌ بالاسم** في حارس النقاء.
 *
 * كلُّ ما تحت `domain/` يستقبل `now` وسيطاً، وكلُّ ما تحت `app/` يستقبل `Clock`. فالساعةُ
 * الحقيقيّةُ تُنشأ هنا وتُمرَّر من `http/server.ts` وحدَه، وتُستبدل في الاختبار بـ`fixedClock`.
 *
 * ولمَ ملفٌّ لسطرين؟ لأنّ البديلَ `new Date()` في المُنادي — وهو ما يجعل الحارسَ يُستثنى
 * ملفاً بعد ملفٍّ حتى لا يمنع شيئاً. والاستثناءُ الواحدُ الذي **لا يُصدّر إلّا ساعةً** يبقى
 * قابلاً للقراءة في سطرٍ واحد: إن كان هذا الملفُّ سليماً فلا ساعةَ مخفيّةً في الخدمة كلِّها.
 */

import type { Clock } from "../domain/time.js";

/** ساعةُ النظام: `now()` نصُّ ISO لأنّ المجالَ لا يعرف `Date` (HANDOFF §16-ب). */
export const systemClock: Clock = Object.freeze({
  now(): string {
    return new Date().toISOString();
  },
});
